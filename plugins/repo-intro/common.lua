-- common.lua — repo-intro 通用配置、零宽水印、Base64 与群聊脱敏工具

return function(jn)
    local M = {}

    function M.cfg_bool(key, default)
        local v = jn.config.get(key)
        if v == nil then return default end
        return v ~= false and v ~= "false" and v ~= "0"
    end

    function M.cfg_num(key, default)
        local v = jn.config.get(key)
        if v == nil or v == "" then return default end
        local n = tonumber(v)
        if n == nil then return default end
        return n
    end

    function M.cfg_string(key, default)
        local v = jn.config.get(key)
        if v == nil or v == "" then return default end
        return tostring(v)
    end

    function M.trim(s)
        if not s then return "" end
        return (tostring(s):gsub("^%s+", ""):gsub("%s+$", ""))
    end

    function M.is_model_entry(e)
        return e ~= nil and (e.kind == "hf" or e.kind == "ms")
            and e.sub ~= "datasets" and e.sub ~= "spaces"
    end

    function M.truncate(str, e)
        local max = M.cfg_num("max_readme_chars", 10000)
        if e and e.kind == "github" then
            max = M.cfg_num("github_readme_max_chars", 30000)
        elseif M.is_model_entry(e) then
            max = M.cfg_num("model_readme_max_chars", 30000)
        end
        if #str > max then return str:sub(1, max) end
        return str
    end

    function M.url_encode(s)
        return (s:gsub("([^%w%-_%.~])", function(c)
            return string.format("%%%02X", c:byte())
        end))
    end

    -- ----------------------------------------------------------------
    -- 零宽水印：将 "Generated by JuanNiang Neo" 编码为零宽字符，防二次总结循环
    -- ----------------------------------------------------------------
    local WM_TEXT = "Generated by JuanNiang Neo"
    local WM_HEAD = "\239\187\191"
    local WM_ZERO = "\226\128\139"
    local WM_ONE = "\226\128\140"
    local WM_LEGACY = "\226\128\139\226\128\140\226\128\141\239\187\191"

    local function wm_encode(text)
        local bits = {}
        for i = 1, #text do
            local b = text:byte(i)
            for k = 7, 0, -1 do
                bits[#bits + 1] = (math.floor(b / 2 ^ k) % 2 == 1) and WM_ONE or WM_ZERO
            end
        end
        return WM_HEAD .. table.concat(bits)
    end

    local function wm_decode_at(raw, pos)
        local out, cur, nbits = {}, 0, 0
        local i = pos
        while true do
            local ch = raw:sub(i, i + 2)
            if ch == WM_ZERO then
                cur = cur * 2; nbits = nbits + 1
            elseif ch == WM_ONE then
                cur = cur * 2 + 1; nbits = nbits + 1
            else
                break
            end
            if nbits == 8 then
                out[#out + 1] = string.char(cur)
                cur, nbits = 0, 0
            end
            i = i + 3
        end
        return table.concat(out)
    end

    function M.wm_own(raw)
        if not raw or raw == "" then return false end
        if raw:find(WM_LEGACY, 1, true) then return true end
        local pos = 1
        while true do
            local p = raw:find(WM_HEAD, pos, true)
            if not p then return false end
            local got = wm_decode_at(raw, p + #WM_HEAD)
            if #got >= 8 and WM_TEXT:sub(1, #got) == got then return true end
            pos = p + #WM_HEAD
        end
    end

    M.WATERMARK = wm_encode(WM_TEXT)

    -- ----------------------------------------------------------------
    -- Base64 解码（分块 flush，避免大 README 触发 gopher-lua registry overflow）
    -- ----------------------------------------------------------------
    local B64_CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    local B64_MAP = {}
    for i = 1, #B64_CHARS do B64_MAP[B64_CHARS:sub(i, i)] = i - 1 end

    function M.b64_decode(s)
        if not s or s == "" then return "" end
        s = s:gsub("%s", ""):gsub("=+$", "")
        local acc, out, n, i = "", {}, #s, 1
        local FLUSH = 1024
        while i <= n do
            local c1 = B64_MAP[s:sub(i, i)]; i = i + 1
            local c2 = B64_MAP[s:sub(i, i)]; i = i + 1
            if not c1 or not c2 then return nil end
            local c3 = (i <= n) and B64_MAP[s:sub(i, i)] or nil
            if c3 then i = i + 1 end
            local c4 = (i <= n) and B64_MAP[s:sub(i, i)] or nil
            if c4 then i = i + 1 end
            out[#out + 1] = string.char(c1 * 4 + math.floor(c2 / 16))
            if c3 then
                out[#out + 1] = string.char((c2 % 16) * 16 + math.floor(c3 / 4))
                if c4 then
                    out[#out + 1] = string.char((c3 % 4) * 64 + c4)
                end
            end
            if #out >= FLUSH then
                acc = acc .. table.concat(out)
                out = {}
            end
        end
        if #out > 0 then acc = acc .. table.concat(out) end
        return acc
    end

    -- ----------------------------------------------------------------
    -- 有效 LLM 结果校验 & 群聊敏感词脱敏
    -- ----------------------------------------------------------------
    function M.has_valid_llm(e)
        if not e or type(e.llm) ~= "table" then return false end
        local t = M.trim(e.llm.title or "")
        local sum = M.trim(e.llm.summary or "")
        return t ~= "" or sum ~= ""
    end

    local GROUP_REPLACE = {
        { "白嫖", "免费获取" },
        { "福利", "资源" },
        { "免费", "开放" },
        { "抽奖", "活动" },
        { "试用", "体验" },
        { "推广", "分享" },
        { "虚假", "不实" },
    }

    local function sanitize_group_text(s)
        if type(s) ~= "string" or s == "" then return s, false end
        local out, changed = s, false
        for _, kv in ipairs(GROUP_REPLACE) do
            local n
            out, n = out:gsub(kv[1], kv[2])
            if n > 0 then changed = true end
        end
        return out, changed
    end

    function M.sanitize_entry_for_group(e)
        local copy, changed = {}, false
        for k, v in pairs(e) do copy[k] = v end
        local function scrub(tbl)
            if type(tbl) ~= "table" then return nil, false end
            local out, any = {}, false
            for k, v in pairs(tbl) do
                if type(v) == "string" then
                    local nv, ch = sanitize_group_text(v)
                    out[k] = nv
                    if ch then any = true end
                else
                    out[k] = v
                end
            end
            return out, any
        end
        local llm, a = scrub(e.llm)
        local meta, b = scrub(e.meta)
        if a then changed = true end
        if b then changed = true end
        if llm then copy.llm = llm end
        if meta then copy.meta = meta end
        return copy, changed
    end

    return M
end

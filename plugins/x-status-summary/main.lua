local function cfg_bool(key, default)
    local v = jn.config.get(key)
    if v == nil then return default end
    if type(v) == "boolean" then return v end
    local s = tostring(v):gsub("^%s+", ""):gsub("%s+$", ""):lower()
    if s == "" then return default end
    return s ~= "false" and s ~= "0" and s ~= "no" and s ~= "off"
end

local function cfg_num(key, default)
    local v = jn.config.get(key)
    if v == nil or v == "" then return default end
    local n = tonumber(v)
    if n == nil then return default end
    return n
end

local function cfg_string(key, default)
    local v = jn.config.get(key)
    if v == nil or v == "" then return default end
    return tostring(v)
end

local function cfg_string_allow_empty(key, default)
    local v = jn.config.get(key)
    if v == nil then return default end
    return tostring(v)
end

local function cfg_id_set(key)
    local v = jn.config.get(key)
    local set = {}
    local function add_tokens(raw)
        for tok in tostring(raw or ""):gmatch("%d+") do
            set[tok] = true
        end
    end
    if type(v) == "table" then
        for _, item in ipairs(v) do
            add_tokens(item)
        end
    elseif type(v) == "string" and v ~= "" then
        add_tokens(v)
    end
    return set
end

local function is_compliance_enabled_for_target(target)
    local base = cfg_bool("compliance_filter", true)
    if not target or target.message_type ~= "group" then
        return base
    end
    local gid = tostring(target.target_id or "")
    if gid == "" or gid == "0" then return base end
    if cfg_id_set("compliance_enable_groups")[gid] then return true end
    if cfg_id_set("compliance_disable_groups")[gid] then return false end
    return base
end

-- --------------------------------------------------------------------
-- 水印：把 "Generated by JuanNiang Neo" 编码成零宽字符，附在标题行尾。
-- 编码：U+FEFF 起头 + 每字节 8 位（U+200B=0 / U+200C=1），肉眼不可见。
-- 转发本机输出时能解码出该串 → 直接忽略，避免二次总结。
-- 兼容旧版固定 4 字符标记（ZWSP+ZWNJ+ZWJ+BOM）。
-- --------------------------------------------------------------------
local WM_TEXT = "Generated by JuanNiang Neo"
local WM_HEAD = "\239\187\191"                                   -- U+FEFF
local WM_ZERO = "\226\128\139"                                   -- U+200B
local WM_ONE = "\226\128\140"                                    -- U+200C
local WM_LEGACY = "\226\128\139\226\128\140\226\128\141\239\187\191"

local function wm_encode(text)
    local bits = {}
    for i = 1, #text do
        local b = text:byte(i)
        for k = 7, 0, -1 do
            bits[#bits + 1] = (math.floor(b / 2 ^ k) % 2 == 1) and WM_ONE or WM_ZERO
        end
    end
    return WM_HEAD .. table.concat(bits)
end

local function wm_decode_at(raw, pos)
    local out, cur, nbits = {}, 0, 0
    local i = pos
    while true do
        local ch = raw:sub(i, i + 2)
        if ch == WM_ZERO then
            cur = cur * 2
            nbits = nbits + 1
        elseif ch == WM_ONE then
            cur = cur * 2 + 1
            nbits = nbits + 1
        else
            break
        end
        if nbits == 8 then
            out[#out + 1] = string.char(cur)
            cur, nbits = 0, 0
        end
        i = i + 3
    end
    return table.concat(out)
end

local function wm_own(raw)
    if not raw or raw == "" then return false end
    if raw:find(WM_LEGACY, 1, true) then return true end
    local pos = 1
    while true do
        local p = raw:find(WM_HEAD, pos, true)
        if not p then return false end
        local got = wm_decode_at(raw, p + #WM_HEAD)
        if #got >= 8 and WM_TEXT:sub(1, #got) == got then return true end
        pos = p + #WM_HEAD
    end
end


-- ====================================================================
-- arxiv-summary arXiv 论文总结插件
-- --------------------------------------------------------------------
-- 识别群聊/私聊中发送的 arXiv 链接（/abs/ /pdf/ /html/、带版本号与
-- 裸 DOI 形式均可），统一归一化为 https://arxiv.org/abs/<id> 抓取
-- 元数据（citation_title / citation_author / citation_abstract /
-- primary-subject），合并为一次 LLM 调用做标题与摘要的中文翻译，
-- 最终按「标题原文 / 标题翻译 / 作者 / 摘要翻译 / 学科」输出。
--
-- 跨消息攒批：同群同一人的链接进入缓冲，攒满阈值（默认 3 篇）立刻
-- 发送，否则窗口到点发送；多篇默认合并转发，每篇一个节点。
-- 抓取失败（网络 / 代理波动 / 404）整批静默，不回任何消息。
-- 全程异步：http.get_async + llm.chat_async，不阻塞事件循环。
-- --------------------------------------------------------------------
-- 防二次总结：标题行附零宽水印（编码 "Generated by JuanNiang Neo"），
-- 转发回群的本机输出会被 wm_own 识别并直接忽略。
-- ====================================================================


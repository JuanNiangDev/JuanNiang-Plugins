-- x-status-summary  X（推特）链接总结插件
-- --------------------------------------------------------------------
-- 识别 x.com / twitter.com 的状态链接（含 /i/status/<id> 形式）。
--   1. 抓 api.fxtwitter.com/status/<id> 的公开 JSON（正文/作者/媒体/文章/引用）
--   2. X 长文（article）= 公众号样式：标题+作者+总结+封面+正文图
--   3. 普通推文 = 作者+一句话标题+总结+链接；信息量不足时原样转发文字+图片
--   4. 引用/回复 = 一并说明「谁说了什么、本条怎么回」
--   5. 推文里的 GitHub 链接 = 单独发一条仓库消息（含 card-5 卡片图）
--   6. 视频 ≤10 分钟且 ≤50MB 以视频消息发送，否则只发链接
-- 全程异步（http/llm/t2i 回调），不阻塞事件循环。
-- ====================================================================


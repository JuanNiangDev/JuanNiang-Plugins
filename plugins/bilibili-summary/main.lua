        if #(m.pages or {}) > 1 then
            out[#out + 1] = "说明：没有获取到任何字幕，请只根据上面的分P标题概括这个合集讲什么（≤200 字）。"
        else
            out[#out + 1] = "说明：没有获取到字幕。"
        end
    end
    return table.concat(out, "\n")
end


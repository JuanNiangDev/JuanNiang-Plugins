local function cfg_bool(key, default)
    local v = jn.config.get(key)
    if v == nil then return default end
    return v ~= false and v ~= "false" and v ~= "0"
end

local function cfg_num(key, default)
    local v = jn.config.get(key)
    if v == nil or v == "" then return default end
    local n = tonumber(v)
    if n == nil then return default end
    return n
end

local function cfg_string(key, default)
    local v = jn.config.get(key)
    if v == nil or v == "" then return default end
    return tostring(v)
end

-- --------------------------------------------------------------------
-- 零宽水印：U+FEFF 起头 + 每字节 8 位（U+200B=0 / U+200C=1）
-- --------------------------------------------------------------------
local WM_TEXT = "Generated by JuanNiang Neo"
local WM_HEAD = "\239\187\191"                                   -- U+FEFF
local WM_ZERO = "\226\128\139"                                   -- U+200B
local WM_ONE = "\226\128\140"                                    -- U+200C
local WM_LEGACY = "\226\128\139\226\128\140\226\128\141\239\187\191"

local function wm_encode(text)
    local bits = {}
    for i = 1, #text do
        local b = text:byte(i)
        for k = 7, 0, -1 do
            bits[#bits + 1] = (math.floor(b / 2 ^ k) % 2 == 1) and WM_ONE or WM_ZERO
        end
    end
    return WM_HEAD .. table.concat(bits)
end

local function wm_decode_at(raw, pos)
    local out, cur, nbits = {}, 0, 0
    local i = pos
    while true do
        local ch = raw:sub(i, i + 2)
        if ch == WM_ZERO then
            cur = cur * 2
            nbits = nbits + 1
        elseif ch == WM_ONE then
            cur = cur * 2 + 1
            nbits = nbits + 1
        else
            break
        end
        if nbits == 8 then
            out[#out + 1] = string.char(cur)
            cur, nbits = 0, 0
        end
        i = i + 3
    end
    return table.concat(out)
end

-- 是否本机输出：解出的 ≥8 字节须是 WM_TEXT 前缀，或命中旧标记
local function wm_own(raw)
    if not raw or raw == "" then return false end
    if raw:find(WM_LEGACY, 1, true) then return true end
    local pos = 1
    while true do
        local p = raw:find(WM_HEAD, pos, true)
        if not p then return false end
        local got = wm_decode_at(raw, p + #WM_HEAD)
        if #got >= 8 and WM_TEXT:sub(1, #got) == got then return true end
        pos = p + #WM_HEAD
    end
end

local WATERMARK = wm_encode(WM_TEXT)

-- --------------------------------------------------------------------
-- 工具函数
-- --------------------------------------------------------------------
local function norm_space(s)
    if not s then return "" end
    return (s:gsub("%s+", " "):gsub("^%s+", ""):gsub("%s+$", ""))
end

local function copy_ctx(ctx)
    local c = {}
    for k, v in pairs(ctx) do c[k] = v end
    return c
end

-- HTML 实体解码（arXiv meta 里主要是 &#39; / &amp;）
local function html_unescape(s)
    if not s or s == "" then return "" end
    s = s:gsub("&#(%d+);", function(n)
        local code = tonumber(n)
        if not code then return "" end
        if code < 128 then return string.char(code) end
        -- UTF-8 编码（仅覆盖常见区间，arXiv 极少出现）
        if code < 2048 then
            return string.char(192 + math.floor(code / 64), 128 + code % 64)
        end
        return string.char(224 + math.floor(code / 4096),
            128 + math.floor(code / 64) % 64, 128 + code % 64)
    end)
    s = s:gsub("&#x(%x+);", function(h)
        local code = tonumber(h, 16)
        if not code then return "" end
        if code < 128 then return string.char(code) end
        return s
    end)
    s = s:gsub("&lt;", "<"):gsub("&gt;", ">")
    s = s:gsub("&quot;", '"'):gsub("&apos;", "'")
    s = s:gsub("&nbsp;", " ")
    s = s:gsub("&amp;", "&")
    return s
end

-- 按 UTF-8 字符数截断
local function truncate_utf8(str, max)
    if not str or str == "" or max <= 0 then return "" end
    local count, i, n = 0, 1, #str
    while i <= n do
        local b = str:byte(i)
        local len = 1
        if b >= 0xF0 then len = 4
        elseif b >= 0xE0 then len = 3
        elseif b >= 0xC0 then len = 2
        end
        if i + len - 1 > n then break end
        count = count + 1
        if count > max then
            return str:sub(1, i - 1)
        end
        i = i + len
    end
    return str
end

-- --------------------------------------------------------------------
-- URL 解析：arXiv 链接 → 规范 id
-- --------------------------------------------------------------------
-- 新式：2504.01538 / 2504.01538v2；老式：hep-th/9901001、math.AG/0601001
-- 兼容 /abs/ /pdf/ /html/ 三种路径与 pdf 扩展名、query 参数
local function parse_urls(raw)
    if not raw or raw == "" then return {} end
    local seen, out = {}, {}
    local pos = 1
    while true do
        local s = raw:find("arxiv.org/", pos, true)
        if not s then break end
        pos = s + 1
        local c = raw:sub(s - 1, s - 1)
        if c == "" or not c:match("%w") then
            local tail = raw:sub(s + #"arxiv.org/", s + #"arxiv.org/" + 120)
            local kind, body = tail:match("^(%a+)/([^%s%?#\"'<>]+)")
            if kind == "abs" or kind == "pdf" or kind == "html" then
                local id = body:match("^([0-9][0-9][0-9][0-9]%.[0-9][0-9][0-9][0-9][0-9]?)")
                if not id then
                    id = body:match("^([%a%-]+%.[A-Z][A-Z]/[0-9][0-9][0-9][0-9][0-9][0-9][0-9])")
                end
                if not id then
                    id = body:match("^([%a%-]+/[0-9][0-9][0-9][0-9][0-9][0-9][0-9])")
                end
                if id and not seen[id] then
                    seen[id] = true
                    out[#out + 1] = {
                        id = id,
                        key = "ax:" .. id,
                        url = "https://arxiv.org/abs/" .. id,
                    }
                end
            end
        end
    end
    return out
end

-- --------------------------------------------------------------------
-- arXiv abs 页解析
-- --------------------------------------------------------------------
local function meta_one(html, name)
    local m = html:match('<meta name="' .. name .. '" content="([^"]*)"')
    if not m then return nil end
    return norm_space(html_unescape(m))
end


local B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local B64IDX = {}
for i = 1, #B64 do B64IDX[B64:sub(i, i)] = i - 1 end

-- base64 解码（GitHub README content 用；稀疏表足够快）
local function b64_decode(s)
    if not s or s == "" then return "" end
    s = s:gsub("[^" .. B64 .. "=]", "")
    local acc_str, out, nacc, bits = "", {}, 0, 0
    local FLUSH = 512
    for i = 1, #s do
        local ch = s:sub(i, i)
        if ch == "=" then break end
        local v = B64IDX[ch]
        if v then
            nacc = nacc * 64 + v
            bits = bits + 6
            if bits >= 8 then
                bits = bits - 8
                out[#out + 1] = string.char(math.floor(nacc / 2 ^ bits) % 256)
                nacc = nacc % 2 ^ bits
            end
        end
        -- 分块 flush，避免大 README 触发 gopher-lua registry overflow
        if #out >= FLUSH then
            acc_str = acc_str .. table.concat(out)
            out = {}
        end
    end
    if #out > 0 then acc_str = acc_str .. table.concat(out) end
    return acc_str
end

local function truncate(s, max)
    if not s then return "" end
    if #s <= max then return s end
    return s:sub(1, max)
end

local function trim(s)
    if not s then return "" end
    return (s:gsub("^%s+", ""):gsub("%s+$", ""))
end

local function utf8_truncate(s, max_bytes)
    if not s then return "" end
    if #s <= max_bytes then return s end
    local sub = s:sub(1, max_bytes)
    -- 剥离尾部残缺的多字节 UTF-8 字符，避免 json.encode 失败
    while #sub > 0 do
        local last = sub:byte(#sub)
        if last < 0x80 then break end
        if last >= 0xC0 then
            sub = sub:sub(1, #sub - 1)
            break
        end
        sub = sub:sub(1, #sub - 1)
    end
    return sub
end

local function decode_json_loose(raw)
    if type(raw) ~= "string" or raw == "" then return nil end
    local s = raw:gsub("```[%w_%-]*\n?", ""):gsub("```", "")
    local ok, t = pcall(jn.json.decode, trim(s))
    if ok and type(t) == "table" then return t end
    local i, j = s:find("%b{}")
    if i and j then
        local ok2, t2 = pcall(jn.json.decode, s:sub(i, j))
        if ok2 and type(t2) == "table" then return t2 end
    end
    return nil
end

-- --------------------------------------------------------------------
-- X 链接解析：x.com / twitter.com / mobile.twitter.com 的 /<user>/status/<id>
-- 以及 /i/status/<id>；同一条消息里去重
-- --------------------------------------------------------------------
local function parse_x_links(raw)
    local out, seen = {}, {}
    if not raw or raw == "" then return out end
    -- 先统一去掉查询串与锚点，避免 ?s=20 之类干扰
    local text = raw:gsub("%?[^%s]*", ""):gsub("#[^%s]*", "")
    local patterns = {
        "x%.com/([%w_]+)/status/(%d+)",
        "twitter%.com/([%w_]+)/status/(%d+)",
        "x%.com/i/status/(%d+)",
        "twitter%.com/i/status/(%d+)",
    }
    for _, pat in ipairs(patterns) do
        local init = 1
        while true do
            local a, b = text:find(pat, init)
            if not a then break end
            local whole = text:sub(a, b)
            local id
            if whole:find("/i/status/", 1, true) then
                id = whole:match("(%d+)$")
            else
                id = whole:match("status/(%d+)$")
            end
            if id and not seen[id] then
                seen[id] = true
                out[#out + 1] = { id = id, url = "https://x.com/i/status/" .. id }
            end
            init = b + 1
        end
    end
    return out
end

-- 从推文 link 列表里挑出 GitHub 仓库（owner/repo）
local function github_repos(links)
    local out, seen = {}, {}
    for _, u in ipairs(links or {}) do
        local owner, repo = u:match("^https?://[w%.]*github%.com/([%w_%-%.]+)/([%w_%-%.]+)")
        if owner and repo then
            repo = repo:gsub("%.git$", "")
            -- 过滤非仓库页面（issues/pull/blob/tree/releases 等）
            local bad = { "issues", "pull", "blob", "tree", "releases", "actions", "wiki", "sponsors", "discussions" }
            local isbad = false
            for _, k in ipairs(bad) do
                if repo == k then isbad = true break end
            end
            local key = owner .. "/" .. repo
            if not isbad and not seen[key] then
                seen[key] = true
                out[#out + 1] = { owner = owner, repo = repo, key = key,
                    url = "https://github.com/" .. owner .. "/" .. repo }
            end
        end
    end
    return out
end


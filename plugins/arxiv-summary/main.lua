local llm_ctx = {}

local function fetch_headers()
    return {
        ["User-Agent"] = cfg_string("ua", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"),
        ["Accept"] = "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        ["Accept-Language"] = "en-US,en;q=0.9,zh-CN;q=0.8",
    }
end

local function submit_fetch(e, ctx)
    local proxy = cfg_string("proxy", "")
    if proxy ~= "" then
        return jn.http.get_async(e.url, ctx, fetch_headers(), proxy)
    end
    return jn.http.get_async(e.url, ctx, fetch_headers())
end

local function start_llm(batch)
    if batch.llm_started then return end
    batch.llm_started = true

    local usable = {}
    for _, i in ipairs(batch.uncached) do
        local e = batch.entries[i]
        if not e.err and e.title then
            usable[#usable + 1] = e
        end
    end
    if #usable == 0 or not cfg_bool("enable_summary", true) or not jn.llm or not jn.llm.available() then
        jn.log.info("[" .. PLUGIN .. "] 跳过 LLM，仅输出元数据")
        compose_and_send(batch)
        return
    end

    local parts = {}
    for idx, e in ipairs(usable) do
        parts[#parts + 1] = paper_input_for_llm(e, idx)
        jn.log.info("[" .. PLUGIN .. "] 送翻论文 " .. e.id .. " 摘要 " .. #(e.abstract or "") .. " 字节")
    end
    local messages = {
        { role = "system", content = llm_system_prompt() },
        { role = "user", content = table.concat(parts, "\n\n") },
    }
    batch.llm_messages = messages
    batch.llm_usable = usable
    local rid = jn.llm.chat_async(messages, { timeout = cfg_num("llm_timeout", 90) })
    if not rid or rid == 0 then
        jn.log.warn("[" .. PLUGIN .. "] llm.chat_async 提交失败，降级为无翻译发送")
        compose_and_send(batch)
        return
    end
    llm_ctx[rid] = batch
end

local function check_batch(batch)
    if batch.pending <= 0 then
        start_llm(batch)
    end
end

local function handle_paper(ctx, result, err)
    local batch = ctx.batch
    local e = batch.entries[ctx.idx]
    local status = result and result.status or 0

    if err then
        local attempt = (ctx.fetch_attempt or 0) + 1
        if attempt <= 1 then
            local c = copy_ctx(ctx)
            c.fetch_attempt = attempt
            local rid = submit_fetch(e, c)
            if rid and rid ~= 0 then return end
        end
        e.err = "请求失败：" .. tostring(err)
        jn.log.warn("[" .. PLUGIN .. "] 抓取失败 id=" .. e.id .. " err=" .. tostring(err))
    elseif status == 404 then
        e.err = "论文不存在"
        jn.log.warn("[" .. PLUGIN .. "] 论文不存在 id=" .. e.id)
    elseif status < 200 or status >= 300 then
        e.err = "HTTP " .. tostring(status)
        jn.log.warn("[" .. PLUGIN .. "] 抓取异常 id=" .. e.id .. " status=" .. tostring(status))
    else
        local p, perr = parse_paper(result.body or "")
        if p then
            e.title = p.title
            e.authors = p.authors
            e.abstract = p.abstract
            e.cats = p.cats
            e.pdf_url = p.pdf_url
            if p.arxiv_id and p.arxiv_id ~= "" and p.arxiv_id ~= e.id then
                jn.log.info("[" .. PLUGIN .. "] citation_arxiv_id=" .. p.arxiv_id .. "（请求 " .. e.id .. "）")
            end
        else
            e.err = perr or "解析失败"
            jn.log.warn("[" .. PLUGIN .. "] 解析失败 id=" .. e.id .. " err=" .. tostring(perr))
        end
    end

    batch.pending = batch.pending - 1
end

function on_http_response(req_id, ctx, result, err)
    if not ctx or not ctx.batch or not ctx.stage then return end
    if ctx.stage == "paper" then
        handle_paper(ctx, result, err)
    end
    check_batch(ctx.batch)
end

local function apply_llm_results(batch, content)
    local cleaned = (content or ""):gsub("```[%w]*\n?", ""):gsub("```", "")
    local parsed = jn.json.decode(cleaned)
    if type(parsed) ~= "table" then
        local body = cleaned:match("{.*}")
        if body then parsed = jn.json.decode(body) end
    end
    local results = {}
    if type(parsed) == "table" and type(parsed.papers) == "table" then
        results = parsed.papers
    end
    if #results == 0 then return false end

    local usable = batch.llm_usable or {}
    local used = {}
    for _, r in ipairs(results) do
        if type(r) == "table" and r.index then
            local e = usable[tonumber(r.index)]
            if e then
                e.title_zh = norm_space(r.title_zh or "")
                e.abstract_zh = norm_space(r.abstract_zh or "")
                cache_set(e)
                used[tonumber(r.index)] = true
            end
        end
    end
    return #results > 0
end

function on_chat_response(req_id, content, err)
    local batch = llm_ctx[req_id]
    if not batch then return end
    llm_ctx[req_id] = nil

    if err and err ~= "" then
        local tries = (batch.llm_retries or 0) + 1
        if tries <= 2 and batch.llm_messages then
            batch.llm_retries = tries
            local rid = jn.llm.chat_async(batch.llm_messages, { timeout = cfg_num("llm_timeout", 90) })
            if rid and rid ~= 0 then
                jn.log.warn("[" .. PLUGIN .. "] LLM 失败重试(" .. tries .. "/2): " .. tostring(err))
                llm_ctx[rid] = batch
                return
            end
        end
        jn.log.warn("[" .. PLUGIN .. "] LLM 翻译失败: " .. tostring(err))
        compose_and_send(batch)
        return
    end

    if not apply_llm_results(batch, content) then
        local tries = (batch.llm_retries or 0) + 1
        if tries <= 1 and batch.llm_messages then
            batch.llm_retries = tries
            jn.log.warn("[" .. PLUGIN .. "] LLM 输出无法解析，重试一次")
            local rid = jn.llm.chat_async(batch.llm_messages, { timeout = cfg_num("llm_timeout", 90) })
            if rid and rid ~= 0 then
                llm_ctx[rid] = batch
                return
            end
        end
        jn.log.warn("[" .. PLUGIN .. "] LLM 输出无法解析，按无翻译发送")
    end

    compose_and_send(batch)
end

-- --------------------------------------------------------------------
-- 攒批与入口
-- --------------------------------------------------------------------
local function build_batch(all)
    local max = cfg_num("max_links", 3)
    local ttl = cfg_num("llm_timeout", 90) * 2
    local entries, uncached = {}, {}
    for _, e in ipairs(all) do
        if #entries >= max then
            jn.log.info("[" .. PLUGIN .. "] 单条链接数超过 " .. max .. "，忽略后续")
            break
        end
        local cached = cache_get(e)
        if cached then
            e.done = true
        else
            local mark = tonumber(jn.cache.get("dedup:" .. e.id))
            if mark and os.time() - mark < ttl then
                e.skipped = true
            else
                jn.cache.set("dedup:" .. e.id, os.time(), ttl)
                e.owned_dedup = true
                uncached[#uncached + 1] = #entries + 1
            end
        end
        entries[#entries + 1] = e
    end
    return entries, uncached
end

local function start_pipeline(target, parsed)
    local entries, uncached = build_batch(parsed)
    if #entries == 0 then return end
    local batch = {
        entries = entries,
        uncached = uncached,
        pending = #uncached,
        target = target,
    }
    if batch.pending == 0 then
        compose_and_send(batch)
        return
    end
    for _, i in ipairs(uncached) do
        local ctx = { batch = batch, idx = i, stage = "paper" }
        local rid = submit_fetch(batch.entries[i], ctx)
        if not rid or rid == 0 then
            batch.entries[i].err = "请求提交失败"
            batch.pending = batch.pending - 1
        end
    end
    if batch.pending <= 0 and not batch.llm_started then
        compose_and_send(batch)
        return
    end
    jn.log.info("[" .. PLUGIN .. "] 批量处理 " .. #uncached .. " 篇 arXiv 论文")
end

local BUF = {}
local buf_seq = 0

local function flush_buffer(key)
    local b = BUF[key]
    if not b then return end
    BUF[key] = nil
    start_pipeline(b.target, b.entries)
end

function on_timer_response(req_id, ctx, result, err)
    if type(ctx) == "table" and ctx.action == "ax_batch_flush" then
        local b = BUF[ctx.key]
        if b and b.seq == ctx.seq then
            jn.log.info("[" .. PLUGIN .. "] 攒批窗口到点，发送 " .. #b.entries .. " 篇")
            flush_buffer(ctx.key)
        end
    end
end

local bot_qq_cache
local function is_self(event)
    if bot_qq_cache == nil then
        local info = jn.onebot11.get_login_info()
        if info and info.user_id then bot_qq_cache = tostring(info.user_id) end
    end
    return bot_qq_cache ~= nil and tostring(event.user_id) == bot_qq_cache
end

function on_message(event)
    if not event then return false, false end
    if is_self(event) then return false, false end
    local raw = event.raw_message or ""
    if raw:sub(1, 1) == "/" then return false, false end
    if wm_own(raw) then return true, false end -- 本机输出（含转发）不二次总结
    if not cfg_bool("enabled", true) then return false, false end
    if cfg_bool("group_only", false) and event.message_type ~= "group" then return false, false end

    local parsed = parse_urls(raw)
    if #parsed == 0 then return false, false end

    local target_id = (event.group_id ~= 0 and event.group_id) or event.user_id
    local key = tostring(target_id) .. ":" .. tostring(event.user_id)
    local b = BUF[key]
    if not b then
        b = {
            entries = {},
            seq = 0,
            target = {
                message_type = event.message_type,
                target_id = target_id,
                message_id = event.message_id,
                reply_quote = cfg_bool("reply_quote", true),
            },
        }
        BUF[key] = b
    end

    local seen = {}
    for _, e in ipairs(b.entries) do seen[e.key] = true end
    for _, e in ipairs(parsed) do
        if not seen[e.key] then
            seen[e.key] = true
            b.entries[#b.entries + 1] = e
        end
    end

    local threshold = math.max(1, cfg_num("batch_threshold", 3))
    local window = cfg_num("batch_window", 60)
    if #b.entries >= threshold or window <= 0 then
        jn.log.info("[" .. PLUGIN .. "] 攒满 " .. #b.entries .. " 篇，立即发送")
        flush_buffer(key)
        return true, false
    end

    local wait = (#b.entries >= 2) and window or cfg_num("single_window", 10)
    if wait <= 0 then
        flush_buffer(key)
        return true, false
    end
    if jn.timer and jn.timer.after then
        buf_seq = buf_seq + 1
        b.seq = buf_seq
        jn.timer.after(wait, { action = "ax_batch_flush", key = key, seq = b.seq })
    else
        flush_buffer(key)
    end
    return true, false
end

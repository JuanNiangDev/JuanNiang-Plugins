-- 学科行：主分类优先，交叉分类依次追加，超过 max_categories 折叠
local function format_cats(cats, max_n)
    if type(cats) ~= "table" or #cats == 0 then return "" end
    max_n = max_n or cfg_num("max_categories", 4)
    if max_n < 1 then max_n = 1 end
    local parts = {}
    for i, c in ipairs(cats) do
        if i > max_n then break end
        local code = c.code or ""
        local zh = CAT_ZH[code]
        if zh then
            parts[#parts + 1] = zh .. " (" .. code .. ")"
        else
            local name = (c.name and c.name ~= "") and c.name or code
            parts[#parts + 1] = name .. " (" .. code .. ")"
        end
    end
    local rest = #cats - max_n
    local line = table.concat(parts, " · ")
    if rest > 0 then line = line .. " 等 " .. #cats .. " 类" end
    return line
end

local function parse_subjects(html)
    local cell = html:match('<td class="tablecell subjects">%s*(.-)%s*</td>')
    if not cell then return {} end

    local primary_name, primary_code
    local pn, pc = cell:match('<span class="primary%-subject">(.-)</span>')
    if pc then
        primary_name = norm_space(html_unescape(pn))
        primary_code = pc
    end

    local text = cell:gsub("<[^>]+>", "")
    local cats, seen = {}, {}
    if primary_code then
        seen[primary_code] = true
        cats[#cats + 1] = { code = primary_code, name = primary_name or "" }
    end
    for raw_name, raw_code in text:gmatch("([^;%(]+)%s*%(([%w%.%-]+)%)") do
        local code = norm_space(raw_code)
        if code ~= "" and not seen[code] then
            seen[code] = true
            cats[#cats + 1] = { code = code, name = norm_space(html_unescape(raw_name)) }
        end
    end
    return cats
end

-- 解析 abs 页：成功返回论文表，失败返回 nil + 原因
local function parse_paper(html)
    if not html or html == "" then return nil, "空响应" end

    local title = meta_one(html, "citation_title")
    if not title or title == "" then
        title = html:match('<h1 class="title mathjax">%s*<span class="descriptor">Title:</span>(.-)</h1>')
        if title then title = norm_space(html_unescape(title:gsub("<[^>]+>", ""))) end
    end
    if not title or title == "" then return nil, "未找到标题" end

    -- 作者：meta 为「姓, 名」，转成「名 姓」展示
    local authors = {}
    for raw_author in html:gmatch('<meta name="citation_author" content="([^"]*)"') do
        local name = norm_space(html_unescape(raw_author))
        local last, first = name:match("^(.-),%s*(.+)$")
        if last and last ~= "" and first and first ~= "" then
            name = norm_space(first .. " " .. last)
        end
        if name ~= "" then authors[#authors + 1] = name end
    end

    local abstract = meta_one(html, "citation_abstract")
    if not abstract or abstract == "" then
        local bq = html:match('<blockquote class="abstract mathjax">(.-)</blockquote>')
        if bq then
            abstract = norm_space(html_unescape(bq:gsub("<[^>]+>", " ")))
            abstract = abstract:gsub("^Abstract:%s*", "")
        end
    end

    local arxiv_id = meta_one(html, "citation_arxiv_id")
    local cats = parse_subjects(html)
    local pdf = meta_one(html, "citation_pdf_url")

    return {
        title = title,
        authors = authors,
        abstract = abstract or "",
        cats = cats,
        arxiv_id = arxiv_id,
        pdf_url = pdf,
    }
end


            names[#names + 1] = i .. "." .. trim(p.part or "")
        end
        out[#out + 1] = "分P标题：" .. table.concat(names, "｜")
    end

    local any = false
    local cap = cnum("max_subtitle_chars", 50000)
    for i, s in ipairs(job.subs or {}) do
        if s and s.text and s.text ~= "" then
            any = true
            local ptitle = trim((job.page_list[i] or {}).part or "")

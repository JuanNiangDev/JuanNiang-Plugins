-- 推文正文里出现的外链统一附在末尾（LLM 容易把链接概括掉；
-- GitHub 链接由仓库消息承载，x/twitter 自身链接跳过）
local function external_links(e, limit, existing)
    local out, seen = {}, {}
    local cand = {}
    for _, u in ipairs(e.links or {}) do cand[#cand + 1] = u end
    -- 长文正文里的裸链接（facets 不一定覆盖到 article 块）
    if e.article then
        for u in (entry_body(e) or ""):gmatch("https?://[%w%-%._~:/%?#%[%]@!%$&'%(%)%*%+,;=]+") do
            cand[#cand + 1] = (u:gsub("[%.,;%)]+$", ""))
        end
    end
    for _, u in ipairs(cand) do
        local low = u:lower()
        local skip = low:find("//x.com/", 1, true) or low:find("//twitter.com/", 1, true)
            or low:find("//github.com/", 1, true)
        local dup = existing ~= nil and existing ~= "" and existing:find(u, 1, true) ~= nil
        if not skip and not seen[u] and not dup then
            seen[u] = true
            out[#out + 1] = u
            if #out >= (limit or 5) then break end
        end
    end
    return out
end

local function compose_tweet(e, llm)
    local lines = {}
    local who = e.screen_name ~= "" and ("@" .. e.screen_name) or e.author_name
    if e.author_name ~= "" and e.screen_name ~= "" then
        who = who .. " | " .. e.author_name
    end
    local mode = (llm and llm.mode) or "summary"
    local title = (llm and llm.title) or ""
    local summary = (llm and llm.summary) or ""

    if mode == "raw" or (title == "" and summary == "") then
        if who ~= "" then lines[#lines + 1] = who end
        if e.text ~= "" then lines[#lines + 1] = e.text end
        if e.llm and e.llm.translation and e.llm.translation ~= "" then
            lines[#lines + 1] = "🔁 中文翻译：" .. e.llm.translation
        end
        lines[#lines + 1] = e.url .. WATERMARK
        return table.concat(lines, "\n")
    end

    if who ~= "" then lines[#lines + 1] = who end
    if title ~= "" then lines[#lines + 1] = title end
    if summary ~= "" then lines[#lines + 1] = summary end
    if e.llm and e.llm.translation and e.llm.translation ~= "" then
        lines[#lines + 1] = "🔁 中文翻译：" .. e.llm.translation
    end
    for _, u in ipairs(external_links(e, 5, table.concat(lines, "\n"))) do
        lines[#lines + 1] = u
    end
    lines[#lines + 1] = e.url .. WATERMARK
    return table.concat(lines, "\n")
end

local function compose_article(e, llm)
    local lines = {}
    local title = (e.article and e.article.title) or ""
    if llm and llm.title and llm.title ~= "" then title = llm.title end
    lines[#lines + 1] = "📰 " .. (title ~= "" and title or "X 长文") .. WATERMARK
    local author = e.author_name ~= "" and ("@" .. e.screen_name .. " | " .. e.author_name) or ("@" .. e.screen_name)
    if author ~= "@" then lines[#lines + 1] = "📖 " .. author end
    local summary = (llm and llm.summary) or ""
    if summary ~= "" then lines[#lines + 1] = summary end
    for _, u in ipairs(external_links(e, 5, table.concat(lines, "\n"))) do
        lines[#lines + 1] = u
    end
    lines[#lines + 1] = "🔗 原文链接：" .. e.url
    return table.concat(lines, "\n")
end

local function compose_repo(repo)
    local lines = {}
    lines[#lines + 1] = "📦 " .. repo.key .. WATERMARK
    local llm = repo.llm or {}
    local desc = llm.desc_cn ~= nil and llm.desc_cn ~= "" and llm.desc_cn
        or (repo.meta and repo.meta.desc) or ""
    if desc ~= "" then
        lines[#lines + 1] = "📝 " .. desc
    elseif llm.title and llm.title ~= "" then
        lines[#lines + 1] = "📝 " .. llm.title
    end
    if llm.summary and llm.summary ~= "" then lines[#lines + 1] = llm.summary end
    lines[#lines + 1] = repo.url
    return table.concat(lines, "\n")
end

local function send_segments(batch, segments)
    local t = batch.target
    if t.message_type == "group" then
        jn.onebot11.send_group_msg(t.target_id, segments)
    else
        jn.onebot11.send_private_msg(t.target_id, segments)
    end
end

-- 同步发送：只有它能拿到失败原因，用来做「图文失败→纯文本」「视频失败→链接」降级。
-- 异步版本是 fire-and-forget，失败只写进宿主日志，插件无从补救。
local function send_segments_sync(batch, segments)
    local t = batch.target
    if t.message_type == "group" then
        return jn.onebot11.send_group_msg_sync(t.target_id, segments)
    end
    return jn.onebot11.send_private_msg_sync(t.target_id, segments)
end

local function media_segments(e, max_images)
    local segs = {}
    if not cfg_bool("send_media", true) then return segs end
    local n = 0
    local prefix = cfg_string("proxy_image_rewrite", "")
    for _, u in ipairs(photo_urls(e.media)) do
        if max_images > 0 and n >= max_images then break end
        local file = u
        if prefix ~= "" then
            if prefix:find("url=", 1, true) then
                file = prefix .. (u:gsub("?", "%%3F"):gsub("&", "%%26"))
            else
                file = prefix .. u:gsub("^https?://", "")
            end
        end
        segs[#segs + 1] = { type = "image", data = { file = file } }
        n = n + 1
    end
    if cfg_bool("video_enabled", true) then
        local v = pick_video(e.media)
        if v then
            local vp = cfg_string("video_url_rewrite", "")
            if vp ~= "" then
                v = vp .. (v:gsub("[^%w%-%.~_/:%?&=]", function(c)
                    return string.format("%%%02X", c:byte())
                end))
            end
            segs[#segs + 1] = { type = "video", data = { file = v } }
        end
    end
    return segs
end


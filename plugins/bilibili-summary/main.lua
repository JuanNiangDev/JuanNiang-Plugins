render_article = function(job)
    local m = job.meta or {}
    local llm = job.llm or {}
    local lines = {}
    local title = trim(m.title or "")
    if title ~= "" then
        lines[#lines + 1] = "📄 " .. title
    end
    if trim(m.author or "") ~= "" then
        lines[#lines + 1] = "👤 " .. m.author
    end
    local link = display_link(job)
    lines[#lines + 1] = "🔗 " .. link
    append_summary_lines(lines, llm)
    local vc = m.video_card
    if type(vc) == "table" and trim(vc.title or "") ~= "" then
        lines[#lines + 1] = "🎬 引用视频：" .. vc.title
        if trim(vc.url or "") ~= "" then lines[#lines + 1] = vc.url end
    end

    -- 水印只挂一次，且不能贴在链接后面：零宽字符会被一起复制，URL 直接失效
    local marked = false
    for i = 1, #lines do
        if lines[i]:sub(1, 3) ~= "🔗 " then
            lines[i] = lines[i] .. WATERMARK
            marked = true
            break
        end
    end
    if not marked then lines[#lines + 1] = WATERMARK end

    local images = {}
    if cbool("send_images", true) then
        local max_i = cnum("max_images", 9)
        if vc and type(vc) == "table" and (vc.cover or "") ~= "" and #images < max_i then
            images[#images + 1] = img_for_send(vc.cover)   -- 引用的视频封面
        end
        for _, url in ipairs(m.images or {}) do
            if #images >= max_i then break end
            local u = img_for_send(url)
            if u ~= "" then images[#images + 1] = u end
        end
    end
    return table.concat(lines, "\n"), images
end


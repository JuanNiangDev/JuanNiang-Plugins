local function fmt_count(n)
    n = tonumber(n)
    if not n or n < 0 then return "0" end
    if n >= 1000 then
        local k = n / 1000
        if k >= 10 then return string.format("%.0fk", k) end
        return string.format("%.1fk", k)
    end
    return tostring(n)
end

local function fill_repo_card(tpl, repo)
    local m = repo.meta or {}
    local llm = repo.llm or {}
    local desc = llm.desc_cn ~= nil and llm.desc_cn ~= "" and llm.desc_cn
        or (m.desc ~= nil and m.desc ~= "") and m.desc or ""
    local data = {
        OWNER = repo.owner,
        REPO = repo.repo,
        DESC = desc,
        URL = repo.url,
        STARS = fmt_count(m.stars),
        FORKS = fmt_count(m.forks),
        ISSUES = fmt_count(m.issues),
        LANG_NAME = (m.lang and m.lang ~= "") and m.lang or "Other",
        AVATAR = (m.avatar ~= nil and m.avatar ~= "") and m.avatar or "",
    }
    local out = tpl
    for k, v in pairs(data) do
        out = out:gsub("{{" .. k .. "}}", function() return tostring(v) end)
    end
    return out
end


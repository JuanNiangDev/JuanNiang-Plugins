-- BV 号：BV + 10 位 base58 字符
local function parse_entries(raw)
    if not raw or raw == "" then return {} end
    local seen, entries = {}, {}
    local function add(e)
        if not e or not e.key then return end
        if seen[e.key] then return end
        seen[e.key] = true
        entries[#entries + 1] = e
    end

    -- 1) 只从 bilibili.com/video/ 链接里取 BV；裸 BV 不再识别
    local pos = 1
    while true do
        local s, e, bv = raw:find("bilibili%.com/video/BV([1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z][1-9A-HJ-NP-Za-km-z])", pos)
        if not s then break end
        bv = "BV" .. bv
        local tail = raw:sub(e + 1, e + 80)
        local pm = tail:match("^[^%s]-[?&]p=(%d+)")
        local p = pm and tonumber(pm) or nil
        add({
            kind = "video", bvid = bv, page = p,
            key = "v:" .. bv .. (p and (":" .. p) or ""),
            url = "https://www.bilibili.com/video/" .. bv .. (p and ("?p=" .. p) or ""),
        })
        pos = e + 1
    end

    -- 2) b23.tv 短链
    pos = 1
    while true do
        local s, e = raw:find("b23%.tv/([%w]+)", pos)
        if not s then break end
        local code = raw:sub(s, e):match("b23%.tv/([%w]+)")
        if code then
            add({
                kind = "b23", code = code,
                key = "b23:" .. code,
                url = "https://b23.tv/" .. code,
            })
        end
        pos = e + 1
    end

    -- 3) opus 专栏 / 动态
    pos = 1
    while true do
        local s, e = raw:find("opus/(%d%d%d%d%d%d%d%d%d+)", pos)
        if not s then break end
        local id = raw:sub(s, e):match("opus/(%d+)$")
        if id then
            add({
                kind = "opus", id = id,
                key = "opus:" .. id,
                url = "https://www.bilibili.com/opus/" .. id,
            })
        end
        pos = e + 1
    end

    -- 4) 旧版专栏 read/cv
    pos = 1
    while true do
        local s, e = raw:find("read/cv(%d+)", pos)
        if not s then break end
        local id = raw:sub(s, e):match("read/cv(%d+)$")
        if id then
            add({
                kind = "read", id = id,
                key = "read:" .. id,
                url = "https://www.bilibili.com/read/cv" .. id,
            })
        end
        pos = e + 1
    end

    return entries
end

-- 小程序卡片：raw 里的 [CQ:json,data=...] → qqdocurl（b23 / bilibili 链接）
local function entries_from_json_cards(raw)
    local out = {}
    if not raw or raw == "" then return out end
    local pos = 1
    while true do
        local s = raw:find("[CQ:json,data=", pos, true)
        if not s then break end
        -- data 一直到该段的 ] 结束（JSON 内部不会出现裸 ] 以外的问题；先取到最后一个 ]）
        local rest = raw:sub(s + #"[CQ:json,data=")
        local seg = rest:match("^(.-)%]")
        if not seg then break end
        local decoded = decode_entities(seg)
        local ok, obj = pcall(function() return jn.json.decode(decoded) end)
        if ok and type(obj) == "table" then
            local meta = obj.meta or {}
            local detail = meta.detail_1 or meta.detail_2 or {}
            local doc = detail.qqdocurl or detail.url or obj.qqdocurl or ""
            if type(doc) == "string" and doc ~= "" then
                for _, e in ipairs(parse_entries(doc)) do
                    e.from_card = true
                    out[#out + 1] = e
                end
            end
        end
        pos = s + #"[CQ:json,data="
    end
    return out
end

-- 去重合并
local function collect_entries(raw)
    local list, seen = {}, {}
    for _, e in ipairs(parse_entries(raw)) do
        if not seen[e.key] then seen[e.key] = true; list[#list + 1] = e end
    end
    for _, e in ipairs(entries_from_json_cards(raw)) do
        if not seen[e.key] then seen[e.key] = true; list[#list + 1] = e end
    end
    return list
end


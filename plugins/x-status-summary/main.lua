-- 收尾：组装并发送
-- --------------------------------------------------------------------
local function finish(batch)
    if batch.sent then return end
    batch.sent = true

    local t = batch.target
    local reply_seg = nil
    -- 引用目标必须是真实消息 ID；0/空会让协议端报 could not quote 并可能导致整条发送失败
    local reply_id = tostring(t.message_id or "")
    if t.reply_quote and reply_id ~= "" and reply_id ~= "0" then
        reply_seg = { type = "reply", data = { id = tostring(t.message_id) } }
    end

    local max_images = cfg_num("max_images", 4)
    local comp_on = batch.compliance_on == true
    local summary_on = cfg_bool("enable_summary", true)
    local blocked_notice_tpl = trim(cfg_string_allow_empty("blocked_notice", DEFAULT_BLOCKED_NOTICE))
    -- 每条推文独立一条消息；视频段必须唯一，单独一条；仓库单独一条
    for _, e in ipairs(batch.entries) do
        if e.blocked and comp_on then
            jn.log.warn(string.format("[x-status] 合规拦截推文/长文 id=%s reason=%s",
                tostring(e.id), tostring(e.block_reason or "")))
            if blocked_notice_tpl ~= "" then
                local nsegs = {}
                if reply_seg then nsegs[#nsegs + 1] = reply_seg end
                nsegs[#nsegs + 1] = { type = "text", data = { text = blocked_notice_tpl .. WATERMARK } }
                send_segments(batch, nsegs)
            end
        elseif e.llm_failed and comp_on then
            jn.log.warn(string.format("[x-status] 内容安全校验失败，按 Fail-Closed 策略跳过输出 id=%s", tostring(e.id)))
        elseif e.llm or (not e.err and not comp_on) then
            local text
            if e.article then
                text = compose_article(e, e.llm)
            else
                text = compose_tweet(e, e.llm)
            end
            local segs = {}
            if reply_seg then segs[#segs + 1] = reply_seg end
            segs[#segs + 1] = { type = "text", data = { text = text } }

            -- 媒体分流：图片跟正文同一条消息，视频必须独占一条（OneBot 限制）
            local videos = {}
            for _, s in ipairs(media_segments(e, max_images)) do
                if s.type == "video" then
                    videos[#videos + 1] = s
                else
                    segs[#segs + 1] = s
                end
            end
            if cfg_string("proxy_image_rewrite", "") == "" and (#segs > 1) then
                jn.log.warn("[x-status] proxy_image_rewrite 未配置，图片可能被协议端拉取失败（建议 https://wsrv.nl/?url=）")
            end
            if e.article and e.article.cover and e.article.cover ~= "" and cfg_bool("send_media", true) then
                local cp = cfg_string("proxy_image_rewrite", "")
                local cf = e.article.cover
                if cp ~= "" then
                    if cp:find("url=", 1, true) then
                        cf = cp .. (cf:gsub("?", "%%3F"):gsub("&", "%%26"))
                    else
                        cf = cp .. cf:gsub("^https?://", "")
                    end
                end
                segs[#segs + 1] = { type = "image", data = { file = cf } }
            end

            -- 有视频但没选中（超时长/超体积/仅一帧）时，至少把视频链接带上
            if #videos == 0 and cfg_bool("video_enabled", true) then
                local has_video = false
                for _, m in ipairs(e.media or {}) do
                    if type(m) == "table" and (m.type == "video" or m.format == "video/mp4") then
                        has_video = true
                    end
                end
                if has_video then
                    segs[#segs + 1] = { type = "text", data = {
                        text = "🎬 视频超限未发送，原推：" .. ((e.url and e.url ~= "") and e.url or "") } }
                end
            end

            local img_n = 0
            for _, s in ipairs(segs) do
                if s.type == "image" then img_n = img_n + 1 end
            end
            jn.log.info(string.format("[x-status] 发送 id=%s：图文 %d 张 + 视频 %d 条",
                tostring(e.id), img_n, #videos))

            -- 先发「正文 + 图片」：失败就降级纯文本，保证总结一定送达
            local ok, err = send_segments_sync(batch, segs)
            if not ok then
                jn.log.warn(string.format("[x-status] 图文发送失败，降级纯文本 id=%s err=%s",
                    tostring(e.id), tostring(err)))
                send_segments(batch, { { type = "text", data = { text = text } } })
            end

            -- 再发视频：失败降级成原推链接，避免「总结到了视频没了」还查不到原因
            for _, v in ipairs(videos) do
                local vok, verr = send_segments_sync(batch, { v })
                if not vok then
                    jn.log.warn(string.format("[x-status] 视频发送失败，降级为链接 id=%s err=%s",
                        tostring(e.id), tostring(verr)))
                    local line = "🎬 视频发送失败，原推："
                        .. ((e.url and e.url ~= "") and e.url or (v.data and v.data.file) or "")
                    send_segments(batch, { { type = "text", data = { text = line } } })
                end
            end
        end
    end

    -- 仓库消息单独一条（测试视频模式不发；主推文被合规拦截或未通过安全校验时不发）
    if not cfg_bool("test_video_only", false) then
    for _, repo in ipairs(batch.repos or {}) do
        local owner_blocked = repo.entry and (repo.entry.blocked or (repo.entry.llm_failed and comp_on))
        if repo.meta and not owner_blocked then
            local rs = {}
            if reply_seg then rs[#rs + 1] = reply_seg end
            rs[#rs + 1] = { type = "text", data = { text = compose_repo(repo) } }
            if repo.card_url and repo.card_url ~= "" then
                local cf = repo.card_url
                -- OneBot 在另一个容器：127.0.0.1:5275 不可达，换成 docker 内网服务名
                cf = cf:gsub("http://127%.0%.0%.1:5275", "http://t2i:8999")
                rs[#rs + 1] = { type = "image", data = { file = cf } }
            end
            send_segments(batch, rs)
        end
    end

    end
    for _, e in ipairs(batch.entries) do
        if e.owned_dedup then jn.cache.del("xdedup:" .. e.id) end
    end
end

local function dec(batch)
    batch.pending = batch.pending - 1
    if batch.pending <= 0 and not batch.llm_waiting then
        finish(batch)
    end
end


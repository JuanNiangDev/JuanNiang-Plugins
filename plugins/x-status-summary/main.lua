local bot_qq_cache
local function is_self(event)
    if bot_qq_cache == nil then
        local info = jn.onebot11.get_login_info()
        if info and info.user_id then bot_qq_cache = tostring(info.user_id) end
    end
    return bot_qq_cache ~= nil and tostring(event.user_id) == bot_qq_cache
end

function on_message(event)
    if not event then return false, false end
    if not cfg_bool("enabled", true) then return false, false end
    if is_self(event) then return false, false end

    local raw = event.raw_message or ""
    if raw:sub(1, 1) == "/" then return false, false end
    if wm_own(raw) then return true, false end
    if cfg_bool("group_only", false) and event.message_type ~= "group" then return false, false end

    local links = parse_x_links(raw)
    if #links == 0 then return false, false end
    local max = cfg_num("max_links", 5)
    if #links > max then
        local cut = {}
        for i = 1, max do cut[i] = links[i] end
        links = cut
    end

    local batch = {
        entries = {}, repos = {}, pending = 0, sent = false,
        target = {
            message_type = event.message_type,
            target_id = (event.group_id ~= 0 and event.group_id) or event.user_id,
            message_id = event.message_id,
            reply_quote = cfg_bool("reply_quote", true),
        },
    }
    batch.compliance_on = is_compliance_enabled_for_target(batch.target)

    local dedup_ttl = 120
    for _, l in ipairs(links) do
        local entry = { id = l.id, url = l.url, media = {}, links = {} }
        local cached = jn.cache.get(cache_key(l.id, batch.compliance_on))
        if type(cached) == "table" then
            entry.blocked = cached.blocked == true
            entry.block_reason = tostring(cached.block_reason or "")
            entry.author_name = cached.author_name or ""
            entry.screen_name = cached.screen_name or ""
            entry.text = cached.text or ""
            entry.media = cached.media or {}
            entry.links = cached.links or {}
            entry.article = cached.article
            entry.llm = cached.llm
            entry.url = cached.url or l.url
            batch.entries[#batch.entries + 1] = entry
            if not entry.blocked then
                start_repo_pipeline(batch, entry)
            end
        else
            local key = "xdedup:" .. l.id
            if jn.cache.get(key) then
                -- 在途去重：同一条推文 2 分钟内只处理一次
                jn.log.info("[x-status] 跳过在途推文 " .. l.id)
            else
                jn.cache.set(key, "1", dedup_ttl)
                entry.owned_dedup = true
                batch.entries[#batch.entries + 1] = entry
                batch.pending = batch.pending + 1
                jn.http.get_async(cfg_string("api_base", "https://api.fxtwitter.com") .. "/status/" .. l.id,
                    { stage = "xmeta", batch = batch, entry = entry }, { ["User-Agent"] = UA },
                    cfg_string("proxy", "") ~= "" and cfg_string("proxy", "") or nil)
            end
        end
    end

    if #batch.entries == 0 then return true, false end
    jn.log.info("[x-status] 处理 " .. #batch.entries .. " 条推文")
    if batch.pending == 0 then finish(batch) end
    return true, false
end



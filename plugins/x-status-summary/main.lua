local function media_list(t)
    local m = t.media
    if type(m) ~= "table" then return {} end
    local all = m.all
    if type(all) ~= "table" then return {} end
    return all
end

local function extract_links(t)
    local out = {}
    local raw = t.raw_text
    local facets = type(raw) == "table" and raw.facets or nil
    if type(facets) == "table" then
        for _, f in ipairs(facets) do
            if type(f) == "table" and f.type == "url" then
                local u = f.replacement or f.original
                if u then out[#out + 1] = u end
            end
        end
    end
    return out
end

local function pick_video(media)
    local max_sec = cfg_num("video_max_seconds", 600)
    local max_mb = cfg_num("video_max_mb", 50)
    local best, best_br = nil, -1
    local fallback = nil
    for _, m in ipairs(media) do
        if type(m) == "table" and (m.type == "video" or m.format == "video/mp4") then
            local dur = tonumber(m.duration) or 0
            if dur > 0 and dur <= max_sec then
                local chosen, chosen_br = nil, -1
                for _, f in ipairs(m.formats or {}) do
                    if type(f) == "table" and f.container == "mp4" and f.url then
                        local br = tonumber(f.bitrate) or 0
                        -- 体积估算：bitrate(bps) × 时长 / 8 / 1e6
                        local mb = (br > 0) and (br * dur / 8 / 1e6) or 0
                        if mb <= max_mb and br > chosen_br then
                            chosen, chosen_br = f.url, br
                        end
                    end
                end
                if chosen then
                    if chosen_br > best_br then best, best_br = chosen, chosen_br end
                elseif not fallback and m.url then
                    fallback = m.url -- 没有 formats（老数据）时退回主 url
                end
            end
        end
    end
    return best or fallback
end

local function photo_urls(media)
    local out = {}
    for _, m in ipairs(media) do
        if type(m) == "table" and (m.type == "photo" or m.type == nil) and m.url then
            out[#out + 1] = m.url
        end
    end
    return out
end

-- 把 fxtwitter 的 tweet JSON 转成插件内部结构
local function parse_tweet(t)
    if type(t) ~= "table" then return nil end
    local author = t.author or {}
    local e = {
        id = tostring(t.id or ""),
        url = t.url or "",
        text = trim(t.text or ""),
        author_name = author.name or "",
        screen_name = author.screen_name or "",
        avatar = author.avatar_url or "",
        media = media_list(t),
        links = extract_links(t),
        lang = t.lang or "",
        quote = nil,
        reply_to = t.replying_to_status or nil,
        article = nil,
    }
    if type(t.article) == "table" then
        local a = t.article
        local cover = nil
        local cm = a.cover_media
        if type(cm) == "table" then
            cover = (cm.media_info or {}).original_img_url or cm.url
        end
        e.article = {
            title = trim(a.title or ""),
            content = a.content or "",
            preview = trim(a.preview_text or ""),
            cover = cover,
            media_entities = a.media_entities or {},
        }
    end
    if type(t.quote) == "table" then
        e.quote = parse_tweet(t.quote)
    end
    return e
end

-- 推文里可见文本（长文用 article.content 的纯文本粗剥）
local function strip_html(s)
    if not s or s == "" then return "" end
    s = s:gsub("<br%s*/?>", "\n"):gsub("</p>", "\n"):gsub("<[^>]+>", "")
    s = s:gsub("&nbsp;", " "):gsub("&amp;", "&"):gsub("&lt;", "<"):gsub("&gt;", ">")
    s = s:gsub("&quot;", "\""):gsub("&#39;", "'")
    return trim(s)
end

-- X 长文正文：content 是 Draft.js 结构 {blocks=[{text=...}]}，不是字符串
local function article_text(content)
    if type(content) == "string" then return strip_html(content) end
    if type(content) == "table" and type(content.blocks) == "table" then
        local out = {}
        for _, b in ipairs(content.blocks) do
            if type(b) == "table" and type(b.text) == "string" then
                local t = trim(b.text)
                if t ~= "" then out[#out + 1] = t end
            end
        end
        return table.concat(out, "\n")
    end
    return ""
end

local function entry_body(e)
    if e.article then
        return article_text(e.article.content)
    end
    return e.text or ""
end


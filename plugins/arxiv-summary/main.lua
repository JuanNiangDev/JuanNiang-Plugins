-- 缓存：一篇论文一条记录（元数据 + 中文翻译）
-- --------------------------------------------------------------------
local function cache_key(e)
    return "paper:" .. e.id
end

local function cache_get(e)
    local v = jn.cache.get(cache_key(e))
    if type(v) ~= "table" then return nil end
    if not v.title or v.title == "" then return nil end
    e.title = v.title
    e.authors = v.authors or {}
    e.abstract = v.abstract or ""
    e.cats = v.cats or {}
    e.pdf_url = v.pdf_url
    e.title_zh = v.title_zh
    e.abstract_zh = v.abstract_zh
    e.done = true
    return v
end

local function cache_set(e)
    jn.cache.set(cache_key(e), {
        title = e.title,
        authors = e.authors,
        abstract = e.abstract,
        cats = e.cats,
        pdf_url = e.pdf_url,
        title_zh = e.title_zh,
        abstract_zh = e.abstract_zh,
    }, cfg_num("cache_hours", 168) * 3600)
end


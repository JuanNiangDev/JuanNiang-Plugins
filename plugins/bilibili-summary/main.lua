    elseif e.kind == "opus" then
        fetch_opus(job)
    elseif e.kind == "read" then
        fetch_read(job)
    else
        send_error(job, "不支持的链接")
        finish_job(job)
    end
end

-- -------------------- opus 解析 --------------------
local function extract_initial_state(html)
    local key = "__INITIAL_STATE__="
    local s = html:find(key, 1, true)
    if not s then return nil end
    local rest = html:sub(s + #key)
    local start = rest:find("{", 1, true)
    if not start then return nil end
    local depth, in_str, esc = 0, false, false
    for i = start, #rest do
        local ch = rest:sub(i, i)
        if in_str then
            if esc then esc = false
            elseif ch == "\\" then esc = true
            elseif ch == '"' then in_str = false end
        else
            if ch == '"' then in_str = true
            elseif ch == "{" then depth = depth + 1
            elseif ch == "}" then
                depth = depth - 1
                if depth == 0 then
                    local ok, obj = pcall(function() return jn.json.decode(rest:sub(start, i)) end)
                    if ok then return obj end
                    return nil
                end
            end
        end
    end
    return nil
end

local function paragraph_text(para)
    local t = para.text or {}
    local nodes = t.nodes or {}
    local words = {}
    for _, n in ipairs(nodes) do
        local ty = n.type
        if ty == "TEXT_NODE_TYPE_WORD" then
            local w = n.word or {}
            words[#words + 1] = w.words or ""
        elseif ty == "TEXT_NODE_TYPE_RICH" then
            local r = n.rich or {}
            words[#words + 1] = r.orig_text or r.text or ""
        elseif ty == "TEXT_NODE_TYPE_FORMULA" then
            local f = n.formula or {}
            words[#words + 1] = f.latex or ""
        end
    end
    return table.concat(words)
end

local function parse_opus(body)
    local st = extract_initial_state(body or "")
    if not st or not st.detail then return nil, "页面结构异常" end
    local det = st.detail
    local mods = {}
    for _, m in ipairs(det.modules or {}) do
        if m.module_type then mods[m.module_type] = m end
    end
    local author = (mods.MODULE_TYPE_AUTHOR or {}).module_author or {}
    local title = ""
    if mods.MODULE_TYPE_TITLE and mods.MODULE_TYPE_TITLE.module_title then
        title = mods.MODULE_TYPE_TITLE.module_title.text or ""
    end
    if title == "" then
        local bt = (det.basic or {}).title or ""
        bt = bt:gsub("%s*%-%s*哔哩哔哩$", "")
        if not bt:find("的动态", 1, true) then title = bt end
    end

    local lines, images, video_card, seen_img = {}, {}, nil, {}
    -- 动态/专栏头图（相册）不在正文 paragraphs 里，而是 MODULE_TYPE_TOP.display.album.pics
    local top = mods.MODULE_TYPE_TOP and mods.MODULE_TYPE_TOP.module_top
    local display = top and top.display
    local album = display and display.album
    if album and type(album.pics) == "table" then
        for _, pic in ipairs(album.pics) do
            local u = normalize_img(pic.url or "")
            if u ~= "" and not seen_img[u] then
                seen_img[u] = true
                images[#images + 1] = u
            end
        end
    end
    local content_mod = mods.MODULE_TYPE_CONTENT
    local paras = content_mod and content_mod.module_content and content_mod.module_content.paragraphs or {}
    for _, para in ipairs(paras) do
        local txt = paragraph_text(para)
        if txt ~= "" then lines[#lines + 1] = txt end
        local pic = para.pic
        if pic and pic.pics then
            for _, p in ipairs(pic.pics) do
                local u = normalize_img(p.url or "")
                if u ~= "" and not seen_img[u] then
                    seen_img[u] = true
                    images[#images + 1] = u
                end
            end
        end
        local card = para.link_card and para.link_card.card
        if card then
            local ugc = card.ugc or card.archive or card.common or card.eva3_video
            if ugc then
                local jump = ugc.jump_url or ""
                local t = ugc.title or ""
                if jump:find("/video/", 1, true) then
                    if jump:sub(1, 2) == "//" then jump = "https:" .. jump end
                    video_card = { title = t, url = jump, cover = normalize_img(ugc.cover or "") }
                end
            elseif card.reserve and (card.reserve.jump_url or ""):find("/video/", 1, true) then
                local jump = card.reserve.jump_url
                if jump:sub(1, 2) == "//" then jump = "https:" .. jump end
                video_card = { title = card.reserve.title or "", url = jump,
                    cover = normalize_img(card.reserve.cover or "") }
            end
            if card.opera and card.opera.jump_url then
                local jump = card.opera.jump_url
                if jump:sub(1, 2) == "//" then jump = "https:" .. jump end
                if not video_card then video_card = { title = card.opera.title or "", url = jump } end
            end
        end
    end

    return {
        title = title,
        author = author.name or "",
        pubdate = author.pub_ts or 0,
        content = table.concat(lines, "\n"),
        images = images,
        video_card = video_card,
    }, nil
end

-- -------------------- read/cv 解析 --------------------
local function parse_read(body)
    local st = extract_initial_state(body or "")
    if st then
        local info = st.readInfo or {}
        local content = html_to_text(info.content or "")
        local imgs = {}
        local banner = normalize_img(info.banner_url or "")
        if banner ~= "" then imgs[#imgs + 1] = banner end
        local raw_html = info.content or ""
        for u in raw_html:gmatch('src="([^"]+)"') do
            local nu = normalize_img(u)
            if nu:find("hdslb.com", 1, true) or nu:find("biliimg.com", 1, true) then
                if #imgs < 20 then imgs[#imgs + 1] = nu end
            end
        end
        if content ~= "" then
            return {
                title = info.title or "",
                author = (info.author or {}).name or "",
                pubdate = num_or_zero(info.publish_time),
                content = content,
                images = imgs,
            }, nil
        end
    end
    -- 兜底：直接解析正文容器
    local title = body:match('<meta property="og:title" content="(.-)"') or body:match("<title>(.-)</title>") or ""
    local desc = body:match('<meta name="description" content="(.-)"') or ""
    local content = html_to_text(body:match('<div class="article%-content"[^>]*>(.-)</div>') or desc)
    if content == "" then return nil, "专栏内容为空" end
    return { title = trim(title), author = "", pubdate = 0, content = content, images = {} }, nil
end

-- -------------------- 字幕归属校验（模型二次判断） --------------------
-- B 站字幕接口会把别人的字幕随机下发给同一个 cid；纯标题词重合度不够可靠，
-- 相关度低时先用一次小请求让模型判断字幕是否属于这条视频，再决定是否总结。
local function has_any_sub(job)
    for _, s in ipairs(job.subs or {}) do
        if s and s.text and s.text ~= "" then return true end
    end
    return false
end

local function needs_classify(job)
    if job.classified then return false end
    if job.entry.kind == "opus" or job.entry.kind == "read" then return false end
    for _, s in ipairs(job.subs or {}) do
        if s and s.text and s.text ~= "" and (s.score or 0) < 3 then return true end
    end
    return false
end

local function classify_messages(job)
    local m = job.meta or {}
    local out = {}
    out[#out + 1] = "标题：" .. trim(m.title or "")
    if trim(m.owner_name or "") ~= "" then out[#out + 1] = "UP 主：" .. m.owner_name end
    if trim(m.desc or "") ~= "" then out[#out + 1] = "简介：" .. truncate_chars(m.desc, 200) end
    for i, s in ipairs(job.subs or {}) do
        if s and s.text and s.text ~= "" then
            local ptitle = trim((job.page_list[i] or {}).part or "")
            out[#out + 1] = "【第" .. tostring(i) .. "P" .. (ptitle ~= "" and (" " .. ptitle) or "") .. " 字幕开头】"
            out[#out + 1] = truncate_chars(s.text, 600)
        end
    end
    local sys = [[你是 B 站字幕归属校验器。你会收到视频标题、UP 主、简介、分P标题，以及若干段字幕开头。逐段判断：这段字幕是否属于这个视频。

判断规则：
- 字幕主题与标题/分P/简介明显无关（例如标题讲考研政治，字幕却讲电影、游戏、美食、综艺、情感）→ relevant=false。
- 字幕明显是歌词/音乐内容（唱歌、押韵、副歌、♪）→ relevant=true，且 lyrics=true。
- 宁缺毋滥：只要字幕主题与标题/分P/简介对不上（例如标题是考研带背，字幕却在评测手机、讲电影、聊综艺），一律 relevant=false；无法确定时也按 relevant=false 处理。
只输出 JSON，不要其它文字：
{"items":[{"index":1,"relevant":true,"lyrics":false}]} ]]
    return {
        { role = "system", content = sys },
        { role = "user", content = table.concat(out, "\n") },
    }
end

-- -------------------- 启动 LLM --------------------
local function start_summary(job)
    local e = job.entry
    local is_article = (e.kind == "opus" or e.kind == "read")

    -- 单 P 无字幕：按需求不写总结，直接渲染
    if not is_article then
        local has_sub = false
        for _, s in ipairs(job.subs or {}) do
            if s and s.text and s.text ~= "" then has_sub = true; break end
        end
        local multi = #(job.meta.pages or {}) > 1
        if not has_sub and not multi then
            job.llm = { no_content = true, summary = "", parts = {}, persona = "" }
            local text, images = render_video(job)
            emit_job_output(job, text, images)
            if subtitle_clean(job) then cache_set(e, { text = text, images = images }) end
            finish_job(job)
            return
        end
    end

    if not (jn.llm and jn.llm.available and jn.llm.available()) then
        jn.log.warn("[" .. PLUGIN .. "] 无可用 LLM，降级为仅元信息")
        local text, images
        if is_article then text, images = render_article(job) else text, images = render_video(job) end
        emit_job_output(job, text, images)
        finish_job(job)
        return
    end

    local user = is_article and article_input(job) or video_input(job)
    local messages = {
        { role = "system", content = llm_system_prompt() },
        { role = "user", content = user },
    }
    job.llm_messages = messages
    local rid = jn.llm.chat_async(messages, { timeout = cnum("llm_timeout", 90) })
    if not rid or rid == 0 then
        jn.log.warn("[" .. PLUGIN .. "] chat_async 提交失败")
        local text, images
        if is_article then text, images = render_article(job) else text, images = render_video(job) end
        emit_job_output(job, text, images)
        finish_job(job)
        return
    end
    llm_jobs[rid] = { jid = job.id, kind = "summary" }
end

-- 先做字幕归属校验（仅相关度低时），再进入总结
start_llm = function(job)
    if needs_classify(job) then
        job.classified = true
        local msgs = classify_messages(job)
        job.classify_messages = msgs
        local rid = jn.llm.chat_async(msgs, { timeout = cnum("llm_timeout", 90) })
        if rid and rid ~= 0 then
            llm_jobs[rid] = { jid = job.id, kind = "classify" }
            return
        end
        jn.log.warn("[" .. PLUGIN .. "] 字幕校验提交失败，直接总结")
    end
    start_summary(job)
end

-- -------------------- HTTP 回调 --------------------
local function handle_resolve(job, result)
    local body = result and result.body or ""
    local bv = body:match("video/(BV[1-9A-HJ-NP-Za-km-z]+)")
    if bv then
        job.entry.kind = "video"
        job.entry.bvid = bv
        job.entry.key = "v:" .. bv ..
            (job.entry.page and (":" .. job.entry.page) or "")
        -- b23 首页带 p 参数时从 URL 文本里补
        if not job.entry.page then
            local p = body:match("[?&]p=(%d+)")
            if p then job.entry.page = tonumber(p) end
        end
        job.entry.url = "https://www.bilibili.com/video/" .. bv ..
            (job.entry.page and ("?p=" .. job.entry.page) or "")
        ensure_buvid(job, function() fetch_view(job) end)
        return
    end
    local opus = body:match('"detail":%s*{%s*"id_str":%s*"(%d+)"')
        or body:match('"opus":%s*{%s*"id":%s*"(%d+)"')
        or body:match("opus/(%d%d%d%d%d%d%d%d%d+)")
    if opus then
        job.entry.kind = "opus"
        job.entry.id = opus
        job.entry.key = "opus:" .. opus
        job.entry.url = "https://www.bilibili.com/opus/" .. opus
        fetch_opus(job)
        return
    end
    local cv = body:match("read/cv(%d+)")
    if cv then
        job.entry.kind = "read"
        job.entry.id = cv
        job.entry.key = "read:" .. cv
        job.entry.url = "https://www.bilibili.com/read/cv" .. cv
        fetch_read(job)
        return
    end
    send_error(job, "短链解析失败")
    finish_job(job)
end

local function handle_view(job, result)
    local data = jn.json.decode(result.body or "")
    if type(data) ~= "table" or data.code ~= 0 or type(data.data) ~= "table" then
        local msg = type(data) == "table" and data.message or "接口异常"
        send_error(job, "视频不存在或已失效（" .. tostring(msg) .. "）")
        finish_job(job)
        return
    end
    local d = data.data
    job.meta = {
        aid = tonumber(d.aid) or 0,
        bvid = d.bvid or job.entry.bvid,
        title = d.title or "",
        owner_name = (d.owner or {}).name or "",
        pubdate = d.pubdate or 0,
        view = (d.stat or {}).view or 0,
        desc = d.desc or "",
        cover = normalize_img(d.pic or ""),
        pages = d.pages or {},
    }
    local pages = job.meta.pages
    if #pages == 0 and d.cid then
        pages = { { cid = d.cid, page = 1, part = d.title or "" } }
        job.meta.pages = pages
    end

    local list = {}
    if job.entry.page then
        local p = pages[job.entry.page]
        if p then list[1] = p end
    else
        local cap = math.max(1, cnum("max_pages", 5))
        for i = 1, math.min(#pages, cap) do list[#list + 1] = pages[i] end
    end
    if #list == 0 then
        send_error(job, "视频分 P 信息缺失")
        finish_job(job)
        return
    end
    job.page_list = list
    job.subs = {}
    job.subtitle_tries = {}
    job.idx = 1
    fetch_player(job)
end

local function handle_player(job, ctx, result)
    local data = jn.json.decode(result.body or "")
    local subs = {}
    if type(data) == "table" and data.code == 0 and type(data.data) == "table" then
        local sub = (data.data.subtitle or {}).subtitles or {}
        for _, s in ipairs(sub) do
            if s.subtitle_url and s.subtitle_url ~= "" then
                subs[#subs + 1] = s
            end
        end
    end
    local chosen
    for _, s in ipairs(subs) do
        if not tostring(s.lan or ""):find("^ai") then chosen = s; break end
    end
    if not chosen and #subs > 0 then chosen = subs[1] end

    if chosen then
        local u = chosen.subtitle_url
        if u:sub(1, 2) == "//" then u = "https:" .. u
        elseif u:sub(1, 7) == "http://" then u = "https://" .. u:sub(8) end
        -- 字幕 JSON 是公开 CDN 文件，不携带 Cookie/Referer。
        local rid = http_get(u, { jid = job.id, stage = "subtitle", idx = ctx.idx }, "", false)
        if rid and rid ~= 0 then return end
    end
    -- 接口会间歇性返回空 subtitles（同一 cid 多次请求结果不同），重试几次
    local attempt = tonumber(ctx.attempt) or 0
    if attempt < PLAYER_RETRIES then
        jn.timer.after(1, { jid = job.id, stage = "player_retry", attempt = attempt + 1 })
        return
    end
    jn.log.info("[" .. PLUGIN .. "] 无可用字幕 P" .. tostring(ctx.idx) .. "（重试 " .. tostring(attempt) .. " 次）")
    job.subs[ctx.idx] = { text = "" }
    next_page(job)
end

-- 提取标题里的中文二元组与英文词，用于判断字幕是否属于这条视频。
-- B 站字幕接口偶发返回其它视频的字幕（同 cid 多次请求结果不同），
-- 用与标题/分P标题的相关度过滤，避免把别人的字幕总结成这条视频。
local function cjk_bigrams(s)
    local chars, i = {}, 1
    local n = #s
    while i <= n do
        local b = s:byte(i)
        local size = 1
        if b >= 240 then size = 4
        elseif b >= 224 then size = 3
        elseif b >= 192 then size = 2 end
        if size == 3 then chars[#chars + 1] = s:sub(i, i + 2) end
        i = i + size
    end
    local grams = {}
    for k = 1, #chars - 1 do
        grams[#grams + 1] = chars[k] .. chars[k + 1]
    end
    return grams
end

-- 英文整词匹配（避免 "AI" 命中 said/again 之类的子串）
local function contains_word(hay, w)
    local pos = 1
    while true do
        local s, e = hay:find(w, pos, true)
        if not s then return false end
        local before = s > 1 and hay:sub(s - 1, s - 1) or ""
        local after = hay:sub(e + 1, e + 1)
        if not before:match("[%w]") and not after:match("[%w]") then return true end
        pos = s + 1
    end
end

local STOP_WORDS = {
    ai = true, up = true, app = true, pro = true, max = true, plus = true,
    video = true, bilibili = true, official = true, tv = true,
}
local STOP_BIGRAMS = {
    ["视频"] = true, ["合集"] = true, ["推荐"] = true, ["教程"] = true,
    ["分享"] = true, ["官方"] = true, ["动态"] = true, ["专栏"] = true,
    -- 高频泛词：单个命中不能证明字幕属于这条视频
    ["可以"] = true, ["我们"] = true, ["你们"] = true, ["他们"] = true,
    ["自己"] = true, ["什么"] = true, ["怎么"] = true, ["这个"] = true,
    ["那个"] = true, ["就是"] = true, ["不是"] = true, ["一个"] = true,
    ["没有"] = true, ["如果"] = true, ["因为"] = true, ["所以"] = true,
    ["但是"] = true, ["然后"] = true, ["现在"] = true, ["时候"] = true,
    ["进行"] = true, ["一些"] = true, ["这样"] = true, ["那样"] = true,
    ["知道"] = true, ["觉得"] = true, ["应该"] = true, ["可能"] = true,
    ["开始"] = true, ["最后"] = true, ["第一"] = true, ["第二"] = true,
    ["内容"] = true, ["字幕"] = true, ["问题"] = true, ["东西"] = true,
    ["事情"] = true, ["地方"] = true, ["时间"] = true, ["大家"] = true,
}

local function relevance_score(text, job, idx)
    if not text or text == "" then return 0 end
    local hay = text:lower()
    -- 只用标题与分P标题做校验：简介常年含泛词（AI、学习、分享），加进来会误判
    local titles = { job.meta and job.meta.title or "" }
    local page = job.page_list[idx]
    if page then titles[#titles + 1] = page.part or "" end
    local score, possible, seen_w, seen_g = 0, 0, {}, {}
    for _, t in ipairs(titles) do
        t = tostring(t or "")
        for raw_w in t:gmatch("[%a][%a%d_%-]+") do
            local w = raw_w:lower()
            if #w >= 3 and not STOP_WORDS[w] and not seen_w[w] then
                seen_w[w] = true
                possible = possible + 1
                if contains_word(hay, w) then score = score + 1 end
            end
        end
        for _, g in ipairs(cjk_bigrams(t)) do
            if not STOP_BIGRAMS[g] and not seen_g[g] then
                seen_g[g] = true
                possible = possible + 1
                if hay:find(g, 1, true) then score = score + 1 end
            end
        end
    end
    -- 标题里的特征词足够多时，至少命中 2 个才算相关，避免单个泛词（如“选择”）误判
    local need = possible >= 3 and 2 or 1
    if score < need then return 0 end
    return score
end

local SUBTITLE_TRIES = 5   -- 字幕与标题不符时重取（B 站会随机下发别人的字幕，多试几次提高命中率）

local function handle_subtitle(job, ctx, result)
    local data = jn.json.decode(result.body or "")
    local text = ""
    if type(data) == "table" and type(data.body) == "table" then
        local lines = {}
        for _, line in ipairs(data.body) do
            local c = trim(line.content or "")
            if c ~= "" then lines[#lines + 1] = c end
        end
        text = table.concat(lines, "，")
    end
    local tries = job.subtitle_tries and job.subtitle_tries[ctx.idx] or 1
    local score = relevance_score(text, job, ctx.idx)
    if text ~= "" and score == 0 and tries < SUBTITLE_TRIES then
        job.subtitle_tries[ctx.idx] = tries + 1
        jn.log.info("[" .. PLUGIN .. "] 字幕与标题不符，重新获取 P" .. tostring(ctx.idx) .. "（" .. tries .. "/" .. SUBTITLE_TRIES .. "）")
        -- 经定时器重入，避免在异步回调里直接递归发起新请求触发 registry overflow
        jn.timer.after(1, { jid = job.id, stage = "subtitle_retry", idx = ctx.idx })
        return
    end
    if text ~= "" and score == 0 then
        -- 与标题零重合：可能是歌词（标题不含歌名），也可能是接口错发的其它视频字幕。
        -- 不直接丢弃，交给模型判断；这类结果不写缓存，下次重新取。
        jn.log.warn("[" .. PLUGIN .. "] 字幕与标题无重合，标记为可疑 P" .. tostring(ctx.idx))
        job.subtitle_lost = true
        job.subs[ctx.idx] = { text = text, weak = true, score = score }
    else
        job.subs[ctx.idx] = { text = text, score = score }
    end
    next_page(job)
end

local function handle_opus(job, result)
    local meta, perr = parse_opus(result and result.body or "")
    if not meta then
        send_error(job, perr or "专栏解析失败")
        finish_job(job)
        return
    end
    job.meta = meta
    start_llm(job)
end

local function handle_read(job, result)
    local body = result and result.body or ""
    local meta, perr = parse_read(body)
    if not meta then
        -- 旧专栏页 301 到 opus，落页已是 opus 结构
        meta, perr = parse_opus(body)
        if meta then
            local oid = body:match('"detail":%s*{%s*"id_str":%s*"(%d+)"')
            if oid then job.entry.url = "https://www.bilibili.com/opus/" .. oid end
        end
    end
    if not meta then
        send_error(job, perr or "专栏解析失败")
        finish_job(job)
        return
    end
    job.meta = meta
    start_llm(job)
end

function on_http_response(req_id, ctx, result, err)
    if not ctx or not ctx.jid then return end
    local job = jobs[ctx.jid]
    if not job then return end
    if ctx.stage == "spi" then
        local next_fn = job.after_spi
        job.after_spi = nil
        if err or not result or (result.status or 0) < 200 or (result.status or 0) >= 300 then
            if next_fn then next_fn() end
            return
        end
        handle_spi(job, result, next_fn)
        return
    end
    if err then
        job.err = tostring(err)
        jn.log.warn("[" .. PLUGIN .. "] 请求失败 stage=" .. tostring(ctx.stage) .. " err=" .. tostring(err))
        send_error(job, "网络请求失败")
        finish_job(job)
        return
    end
    local status = result and result.status or 0
    if status < 200 or status >= 300 then
        jn.log.warn("[" .. PLUGIN .. "] HTTP " .. tostring(status) .. " stage=" .. tostring(ctx.stage))
        send_error(job, "接口返回 HTTP " .. tostring(status))
        finish_job(job)
        return
    end

    if ctx.stage == "resolve" then
        handle_resolve(job, result)
    elseif ctx.stage == "view" then
        handle_view(job, result)
    elseif ctx.stage == "player" then
        handle_player(job, ctx, result)
    elseif ctx.stage == "subtitle" then
        handle_subtitle(job, ctx, result)
    elseif ctx.stage == "opus" then
        handle_opus(job, result)
    elseif ctx.stage == "read" then
        handle_read(job, result)
    end
end

-- 定时器回调（字幕接口重试）
function on_timer_response(req_id, ctx, result, err)
    if not ctx then return end
    if ctx.stage == "send_pump" then
        pump_send_queue()
        return
    end
    if ctx.stage == "queue_watchdog" then
        local q = queues[ctx.ck]
        local job = ctx.jid and jobs[ctx.jid] or nil
        if q and q.running and q.current_jid == ctx.jid and job then
            jn.log.warn("[" .. PLUGIN .. "] 任务超时未结束，强制推进队列 jid=" .. tostring(ctx.jid) .. " ck=" .. tostring(ctx.ck))
            finish_job(job)
        end
        return
    end
    if not ctx.jid then return end
    local job = jobs[ctx.jid]
    if not job then return end
    if ctx.stage == "player_retry" then
        fetch_player(job, tonumber(ctx.attempt) or 1)
    elseif ctx.stage == "subtitle_retry" then
        local ok, perr = pcall(fetch_player, job)
        if not ok then
            jn.log.warn("[" .. PLUGIN .. "] 字幕重取失败，跳过该 P: " .. tostring(perr))
            job.subs[ctx.idx] = job.subs[ctx.idx] or { text = "" }
            next_page(job)
        end
    end
end

-- -------------------- LLM 回调 --------------------
function on_chat_response(req_id, content, err)
    local meta = llm_jobs[req_id]
    if not meta then return end
    llm_jobs[req_id] = nil
    local job = jobs[meta.jid]
    if not job then return end

    -- 字幕归属校验结果：与视频无关且不是歌词的段直接剔除
    if meta.kind == "classify" then
        if err and err ~= "" then
            jn.log.warn("[" .. PLUGIN .. "] 字幕校验失败，跳过校验: " .. tostring(err))
            start_summary(job)
            return
        end
        local cleaned = (content or ""):gsub("```[%w]*\n?", ""):gsub("```", "")
        local ok, parsed = pcall(function() return jn.json.decode(cleaned) end)
        local items = ok and type(parsed) == "table" and parsed.items or nil
        if type(items) ~= "table" then
            jn.log.warn("[" .. PLUGIN .. "] 字幕校验输出无法解析: " .. tostring(cleaned):sub(1, 160))
        end
        if type(items) == "table" then
            for _, it in ipairs(items) do
                local idx = tonumber(it.index)
                local sub = idx and job.subs[idx]
                if sub and sub.text and sub.text ~= "" and it.relevant == false and it.lyrics ~= true then
                    jn.log.warn("[" .. PLUGIN .. "] 校验判定字幕不属于视频，剔除 P" .. tostring(idx))
                    sub.text = ""
                    job.subtitle_lost = true
                end
            end
        end
        start_summary(job)
        return
    end

    if err and err ~= "" then
        local tries = (job.llm_retries or 0) + 1
        if tries <= 1 and job.llm_messages then
            job.llm_retries = tries
            local rid = jn.llm.chat_async(job.llm_messages, { timeout = cnum("llm_timeout", 90) })
            if rid and rid ~= 0 then
                llm_jobs[rid] = { jid = meta.jid, kind = "summary" }
                jn.log.warn("[" .. PLUGIN .. "] LLM 失败重试: " .. tostring(err))
                return
            end
        end
        jn.log.warn("[" .. PLUGIN .. "] LLM 失败: " .. tostring(err))
        job.llm = { no_content = true, summary = "", parts = {}, persona = "" }
    else
        local cleaned = (content or ""):gsub("```[%w]*\n?", ""):gsub("```", "")
        local ok, parsed = pcall(function() return jn.json.decode(cleaned) end)
        if ok and type(parsed) == "table" then
            local no_content = parsed.no_content == true
            local summary = clamp_chars(trim(parsed.summary or ""), cnum("summary_max_chars", 300))
            local persona = clamp_chars(trim(parsed.persona or ""), cnum("persona_max_chars", 600))
            if no_content then
                summary, persona = "", ""
            elseif cstr("summary_style", "objective") == "persona" and persona == "" and summary ~= "" then
                persona, summary = summary, ""   -- 模型漏填 persona 时用 summary 兜底
            end
            job.llm = { no_content = no_content, summary = summary, persona = persona }
        else
            jn.log.warn("[" .. PLUGIN .. "] LLM 输出非 JSON，降级")
            job.llm = { no_content = true, summary = "", persona = "" }
        end
    end

    local is_article = (job.entry.kind == "opus" or job.entry.kind == "read")
    local text, images
    if is_article then text, images = render_article(job) else text, images = render_video(job) end
    emit_job_output(job, text, images)
    if subtitle_clean(job) then cache_set(job.entry, { text = text, images = images }) end
    finish_job(job)
end

-- --------------------------------------------------------------------
-- 队列推进
-- --------------------------------------------------------------------
local function run_next(ck)
    local q = queues[ck]
    if not q or q.running then return end
    q.idx = q.idx + 1
    local entry = q.items[q.idx]
    if not entry then
        queues[ck] = nil
        return
    end
    q.running = true
    local job = new_job(q.target, entry)
    q.current_jid = job.id
    -- 队列看门狗：任务异常中断未调 finish_job 时，超时后强制推进，避免整个群队列永久卡死
    jn.timer.after(QUEUE_WATCHDOG_SECONDS, { stage = "queue_watchdog", ck = ck, jid = job.id })
    start_entry(job)
end

advance_queue = function(target)
    local ck = chat_key(target)
    local q = queues[ck]
    if not q then return end
    q.running = false
    run_next(ck)
end


local bot_qq_cache
local function is_self(event)
    if bot_qq_cache == nil then
        local info = jn.onebot11.get_login_info()
        if info and info.user_id then bot_qq_cache = tostring(info.user_id) end
    end
    return bot_qq_cache ~= nil and tostring(event.user_id) == bot_qq_cache
end

local function group_allowed(gid)
    local list = jn.config.get("target_groups")
    if type(list) ~= "table" or #list == 0 then return true end
    for _, v in ipairs(list) do
        if tostring(v) == tostring(gid) then return true end
    end
    return false
end

function on_message(event)
    if not event then return false, nil end
    if not cbool("enabled", true) then return false, nil end
    if event.message_type ~= "group" and event.message_type ~= "private" then return false, nil end
    if is_self(event) then return false, nil end

    local gid = tonumber(event.group_id) or 0
    if event.message_type == "group" and not group_allowed(gid) then return false, nil end

    local raw = event.raw_message or ""
    if wm_own(raw) then return false, nil end
    -- 只识别 b23.tv / bilibili.com；裸 BV 号和其他站点不触发
    if not (raw:find("b23.tv", 1, true) or raw:find("bilibili.com", 1, true)) then
        return false, nil
    end
    local entries = collect_entries(raw)
    if #entries == 0 then return false, nil end
    local max = math.max(1, cnum("max_links", 3))
    if #entries > max then
        jn.log.info("[" .. PLUGIN .. "] 单条链接数超过 " .. tostring(max) .. "，忽略后续")
        while #entries > max do table.remove(entries) end
    end

    local target = {
        message_type = event.message_type,
        target_id = event.message_type == "group" and gid or (tonumber(event.user_id) or 0),
        message_id = event.message_id,
        reply_quote = cbool("reply_quote", true),
    }

    -- 缓存命中 / 异步队列统一纳入本条消息的 batch（支持合并转发开关与阈值）
    local slots, rest = {}, {}
    for _, e in ipairs(entries) do
        local cached = cache_get(e)
        if cached then
            slots[#slots + 1] = { cached = cached }
        elseif jn.cache.get("lock:" .. e.key) then
            jn.log.info("[" .. PLUGIN .. "] 同一内容正在处理或刚发过，跳过 " .. e.key)
        else
            jn.cache.set("lock:" .. e.key, 1, 120)
            slots[#slots + 1] = { entry = e }
            rest[#rest + 1] = e
        end
    end
    if #slots == 0 then return cbool("consume_matched", true), nil end

    local threshold = math.max(1, cnum("merge_threshold", 1))
    local batch = {
        target = target,
        total = #slots,
        done = 0,
        results = {},
        want_forward = cbool("merge_forward", true) and #slots >= threshold,
        quoted_sent = false,
        flushed = false,
    }
    for idx, slot in ipairs(slots) do
        if slot.cached then
            if batch.want_forward then
                batch.results[idx] = { text = slot.cached.text, images = slot.cached.images }
            else
                send_payload(target, slot.cached.text, slot.cached.images, not batch.quoted_sent)
                batch.quoted_sent = true
            end
            batch.done = batch.done + 1
        else
            slot.entry._batch = batch
            slot.entry._batch_order = idx
        end
    end
    if batch.want_forward and batch.done >= batch.total and not batch.flushed then
        batch.flushed = true
        deliver_batch(batch)
    end
    if #rest == 0 then return cbool("consume_matched", true), nil end

    local ck = chat_key(target)
    local q = queues[ck]
    if q then
        for _, e in ipairs(rest) do q.items[#q.items + 1] = e end
    else
        queues[ck] = { items = rest, idx = 0, target = target, running = false }
    end
    run_next(ck)
    -- 命中 B 站链接后默认接管消息，避免 Agent 再对链接本身回复
    return cbool("consume_matched", true), nil
end

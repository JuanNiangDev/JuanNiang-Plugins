            if s.weak then
                out[#out + 1] = "（注意：这段字幕与标题/分P标题几乎无重合，可能是 B 站接口错发的其它视频字幕。先判断是不是歌词：歌词照常总结；明显无关则按提示置 no_content。）"
            end
        end
    end
    if any and #(job.subs or {}) > 1 then
        out[#out + 1] = "说明：以上多个 P 的字幕请合并成一个整体总结，不要逐 P 分条。"
    end

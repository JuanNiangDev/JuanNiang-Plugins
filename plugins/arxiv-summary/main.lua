index 与输入编号一一对应（从 1 开始），不得遗漏任何一篇。]]
end

local function paper_input_for_llm(e, idx)
    local s = "【论文 " .. idx .. "】"
    s = s .. "\n标题：" .. (e.title or "")
    local abs = e.abstract or ""
    local max = cfg_num("max_abstract_chars", 6000)
    if max > 0 then abs = truncate_utf8(abs, max) end
    if abs ~= "" then s = s .. "\n摘要：" .. abs end
    return s
end


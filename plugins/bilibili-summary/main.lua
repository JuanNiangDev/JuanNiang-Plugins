-- 链接展示：full=完整链接；bv=视频 BV 号、专栏优先 b23 短链
local function display_link(job)
    local e = job.entry or {}
    local mode = cstr("link_style", "0")
    if mode ~= "1" and mode ~= "bv" then
        return e.url or ""
    end
    if e.kind == "video" and e.bvid and e.bvid ~= "" then
        return e.bvid .. (e.page and ("?p=" .. e.page) or "")
    end
    if e.kind == "opus" and e.id then
        return "https://www.bilibili.com/opus/" .. e.id
    end
    if e.kind == "read" and e.id then
        return "https://www.bilibili.com/read/cv" .. e.id
    end
    return e.url or ""
end

local function video_url(meta, page)
    local bvid = meta.bvid or ""
    if bvid == "" then return "" end
    if page then return "https://www.bilibili.com/video/" .. bvid .. "?p=" .. tostring(page) end
    return "https://www.bilibili.com/video/" .. bvid
end

local function append_summary_lines(lines, llm)

local function trim(s)
    if not s then return "" end
    return (tostring(s):gsub("^%s+", ""):gsub("%s+$", ""))
end

-- 按 UTF-8 字符数截断（不切断多字节序列）
local function truncate_chars(s, max)
    s = tostring(s or "")
    if max <= 0 then return "" end
    local i, count = 1, 0
    local n = #s
    while i <= n do
        if count >= max then return s:sub(1, i - 1) end
        local b = s:byte(i)
        local size = 1
        if b >= 240 then size = 4
        elseif b >= 224 then size = 3
        elseif b >= 192 then size = 2 end
        i = i + size
        count = count + 1
    end
    return s
end

-- 截断并补省略号（用于总结文本超长兜底）
local function clamp_chars(s, max)
    s = tostring(s or "")
    local cut = truncate_chars(s, max)
    if cut ~= s then return cut .. "…" end
    return cut
end

-- HTML 实体 + CQ 转义还原
local function decode_entities(s)
    s = tostring(s or "")
    s = s:gsub("&#44;", ","):gsub("&#91;", "["):gsub("&#93;", "]")
    s = s:gsub("&#40;", "("):gsub("&#41;", ")")
    s = s:gsub("&#39;", "'"):gsub("&#34;", '"'):gsub("&quot;", '"')
    s = s:gsub("&#61;", "="):gsub("&amp;", "&")
    s = s:gsub("\\/", "/")
    return s
end

-- 去 HTML 标签 → 纯文本
local function html_to_text(html)
    local t = tostring(html or "")
    t = t:gsub("<script[^>]*>.-</script>", " ")
    t = t:gsub("<style[^>]*>.-</style>", " ")
    t = t:gsub("<br%s*/?>", "\n")
    t = t:gsub("</p>", "\n")
    t = t:gsub("<[^>]+>", "")
    t = decode_entities(t)
    t = t:gsub("[ \t]+", " "):gsub("\n%s*\n+", "\n\n")
    return trim(t)
end

local function num_or_zero(v)
    local n = tonumber(v)
    if n == nil then return 0 end
    return n
end

local function fmt_count(n)
    n = num_or_zero(n)
    if n >= 100000000 then return string.format("%.1f亿", n / 100000000) end
    if n >= 10000 then return string.format("%.1f万", n / 10000) end
    return tostring(n)
end

local function fmt_time(ts)
    ts = num_or_zero(ts)
    if ts <= 0 then return "" end
    return os.date("%Y-%m-%d %H:%M", ts)
end

local function normalize_img(url)
    if not url or url == "" then return "" end
    url = decode_entities(url)
    if url:sub(1, 2) == "//" then return "https:" .. url end
    if url:sub(1, 7) == "http://" then return "https://" .. url:sub(8) end
    return url
end

-- 图片可选走代理前缀（如 wsrv.nl/?url=）
local function img_for_send(url)
    url = normalize_img(url)
    if url == "" then return "" end
    local prefix = cstr("image_proxy_prefix", "")
    if prefix ~= "" then
        return prefix .. url
    end
    return url
end


local function compact_authors(authors)
    if type(authors) ~= "table" or #authors == 0 then return "" end
    local n = cfg_num("max_authors", 3)
    if n < 1 then n = 1 end
    if #authors > n then
        local head = {}
        for i = 1, n do head[i] = authors[i] end
        return table.concat(head, ", ") .. " et al."
    end
    return table.concat(authors, ", ")
end

local function compose_section(e)
    local lines = {}
    lines[#lines + 1] = "📄 " .. (e.title or "") .. WATERMARK

    if e.title_zh and e.title_zh ~= "" then
        lines[#lines + 1] = "🌏 " .. e.title_zh
    end

    local au = compact_authors(e.authors)
    if au ~= "" then
        lines[#lines + 1] = "👥 " .. au
    end

    if e.abstract_zh and e.abstract_zh ~= "" then
        lines[#lines + 1] = "🧠 " .. e.abstract_zh
    elseif e.abstract and e.abstract ~= "" then
        -- 翻译不可用时回退英文摘要（截断，避免刷屏）
        lines[#lines + 1] = "🧠 " .. truncate_utf8(e.abstract, 1200)
    end

    local cat_line = format_cats(e.cats)
    if cat_line ~= "" then
        lines[#lines + 1] = "🏷️ " .. cat_line
    end

    local links = "🔗 https://arxiv.org/abs/" .. e.id
    if e.pdf_url and e.pdf_url ~= "" then
        links = links .. " · " .. e.pdf_url
    else
        links = links .. " · https://arxiv.org/pdf/" .. e.id
    end
    lines[#lines + 1] = links

    return table.concat(lines, "\n")
end

-- 机器人身份（转发节点昵称兜底）
local function bot_identity()
    local info = jn.onebot11.get_login_info()
    local uin = info and info.user_id or 0
    local nick = info and info.nickname or ""
    if not nick or nick == "" then nick = "Bot" end
    return tostring(uin), tostring(nick)
end

local function deliver(batch)
    local entries = {}
    for _, e in ipairs(batch.entries) do
        if not e.skipped and not e.err and e.title and e.title ~= "" then
            entries[#entries + 1] = e
        end
    end
    if #entries == 0 then return end -- 全部失败：静默（不回任何消息）

    local t = batch.target
    local threshold = math.max(2, cfg_num("batch_threshold", 3))
    local want_forward = cfg_bool("merge_forward", true) and #entries >= threshold
    local can_forward = (t.message_type == "group" and jn.onebot11.send_group_forward_msg_sync ~= nil)
        or (t.message_type ~= "group" and jn.onebot11.send_private_forward_msg_sync ~= nil)

    if want_forward and can_forward then
        local uin, nick = bot_identity()
        local custom = cfg_string("forward_sender_name", "")
        if custom ~= "" then nick = custom end
        local nodes = {}
        for _, e in ipairs(entries) do
            nodes[#nodes + 1] = {
                user_id = uin,
                nickname = nick,
                content = { { type = "text", data = { text = compose_section(e) } } },
            }
        end
        local _, ferr
        if t.message_type == "group" then
            _, ferr = jn.onebot11.send_group_forward_msg_sync(t.target_id, nodes)
        else
            _, ferr = jn.onebot11.send_private_forward_msg_sync(t.target_id, nodes)
        end
        if ferr == nil then return end
        jn.log.warn("[" .. PLUGIN .. "] 合并转发失败，改用普通消息: " .. tostring(ferr))
    end

    -- 普通消息：每篇一条，首条带引用
    for i, e in ipairs(entries) do
        local segs = { { type = "text", data = { text = compose_section(e) } } }
        if i == 1 and t.reply_quote and t.message_id ~= nil
            and tostring(t.message_id) ~= "" and tostring(t.message_id) ~= "0" then
            table.insert(segs, 1, { type = "reply", data = { id = tostring(t.message_id) } })
        end
        if t.message_type == "group" then
            jn.onebot11.send_group_msg(t.target_id, segs)
        else
            jn.onebot11.send_private_msg(t.target_id, segs)
        end
    end
end

local function compose_and_send(batch)
    for _, e in ipairs(batch.entries) do
        if e.owned_dedup then
            jn.cache.del("dedup:" .. e.id)
        end
    end
    deliver(batch)
end

